/**
 * Сколько повторов дневной потолок ещё разрешает.
 *
 * Сделанное сегодня считается по состоянию самих карточек, а не по журналу:
 * очередь и так собирается из состояний, и они уже содержат ответ — единица,
 * которую сегодня оценили, несёт `last_review` этого учебного дня. Второй
 * источник о том же (журнал) пришлось бы тянуть через все вызовы очереди и
 * держать в согласии с первым.
 *
 * Считаем Review и Relearning: и то и другое — повтор созревшей карточки
 * (в Relearning попадают ТОЛЬКО из Review). Learning не в счёт — это сегодняшнее
 * знакомство и его отработка, у них свой лимит (norms.ts::NEW_PER_DAY, NEW_PER_LESSON) и своя
 * задача. Выпуск вчерашнего слова в Review учтётся как повтор — это тоже
 * извлечение из памяти, и на фоне 180 единичные карточки ничего не решают.
 */
function reviewsLeftToday(items: StudyItem[], now: Date): number {
  const сегодня = dayKey(now)
  const сделано = items.filter(i =>
    (i.fsrs.state === State.Review || i.fsrs.state === State.Relearning) &&
    i.fsrs.last_review && dayKey(i.fsrs.last_review) === сегодня).length
  return Math.max(0, MAX_REVIEW_PER_DAY - сделано)
}

function shuffle<T>(arr: T[]): T[] {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/**
 * Сколько дней карточка ждёт переработки, прежде чем вернуться в уроки без неё.
 *
 * Контур замкнут через колоду, и обе его половины видны в коде: приложение
 * ставит `leech: ДАТА` (store.ts::leechTransition), инструмент колоды
 * `tools/пиявки.mjs` отбирает карточки ровно по этому полю, переписывает
 * примеры/мнемонику/ловушки и СНИМАЕТ поле (`{ ключ: 'leech' }` в `применить`),
 * проставляя `reformulated`. Слияние при синхронизации берёт за базу удалённый
 * фронтматтер (yamlfm.ts::mergeCard — наш вклад только fsrs-блоки и
 * my_sentence), поэтому снятая метка доезжает до приложения и карточка
 * возвращается в очередь сама, со своей историей и своим расписанием: `fsrs`
 * инструмент не трогает принципиально.
 *
 * Но у контура есть дыра, и карантин обязан её учитывать. Инструмент берёт
 * только словарные карточки: у error/grammar/math ответ лежит в `choices`, и
 * менять предложение отдельно от вариантов контракт колоды запрещает — такие
 * пиявки он называет вслух и оставляет тьютору. Плюс инструмент вообще может не
 * запускаться неделями. Бессрочный карантин означал бы, что слово молча
 * выпадает из подготовки навсегда, — а это худшее из всего, что здесь можно
 * сделать: за 43 дня до экзамена (21.08 → 03.10) из практики исчезли бы именно
 * те слова, которые не выучены.
 *
 * Семь дней — передышка самого инструмента (`ПЕРЕДЫШКА_ДНЕЙ` в пиявки.mjs:
 * переработанную карточку он не трогает неделю, давая новой формулировке
 * показать себя). Столько же ждёт и приложение: не забрали за неделю — значит
 * машина эту карточку не возьмёт, и слово возвращается в уроки как есть, а не
 * пропадает. Флаг при этом остаётся: отчёт и метрики продолжают её показывать.
 */
export const LEECH_QUARANTINE_DAYS = 7

/**
 * Карточка изъята из уроков и ждёт переработки.
 *
 * Флаг пиявки ставился и снимался, но на состав урока не влиял никак: слово,
 * про которое уже доказано, что повторение его не лечит, крутилось в очереди
 * наравне со всеми. Замер живой колоды 21.08.2026: 11 карточек с флагом
 * (attribute, concise, corroborate, derive, facilitate, implication, imply,
 * infer, plausible, substantial, undermine) съели 185 показов из 637 за всю
 * историю и 57 из 153 за последние две недели — 37% работы уходило в слова,
 * которым нужна не ещё одна встреча, а другой материал.
 *
 * Дата в поле — начало карантина. Нечитаемая или пустая дата карантина не
 * открывает: без опоры на календарь срок не ограничить, а бессрочно вынимать
 * слово из подготовки нельзя (см. LEECH_QUARANTINE_DAYS).
 */
export function inRework(v: CardView, now: Date = new Date()): boolean {
  const день = (v.leech || '').trim()
  if (!/^\d{4}-\d{2}-\d{2}$/.test(день)) return false
  return dayKey(now) < addDaysKey(день, LEECH_QUARANTINE_DAYS)
}

/**
 * Развёртка колоды в учебные единицы (карточка × навык).
 * prep-навык подключается, когда слово уже знакомо (recall в Review) —
 * или сразу, если prep-график уже начат (не бросаем начатое).
 *
 * Карточка в переработке (`inRework`) единиц не даёт вовсе — ни уроку, ни
 * счётчикам, ни прогнозу нагрузки. Изъятие живёт именно здесь, а не в
 * `buildQueue`: убери её только из очереди — и главный экран продолжил бы
 * обещать повтор, которого урок не даст. Из колоды и из отчётности карточка при
 * этом никуда не девается: `metrics.leeches`, списки `report.ts` и разбивка
 * `byState` считают по карточкам, а не по учебным единицам.
 */
export function expandItems(cards: CardView[], now: Date = new Date()): StudyItem[] {
  const items: StudyItem[] = []
  for (const c of cards) {
    if (c.suspended || inRework(c, now)) continue
    items.push({ view: c, skill: 'recall', fsrs: c.fsrs })
    if (c.prep && c.fsrsPrep) {
      const started = c.fsrsPrep.state !== State.New
      if (started || c.fsrs.state === State.Review) {
        items.push({ view: c, skill: 'prep', fsrs: c.fsrsPrep })
      }
    }
  }
  return items
}

export const itemKey = (i: StudyItem) => `${i.view.path}#${i.skill}`

/**
 * Новые единицы в порядке ввода: сначала error/grammar (доказанные пробелы), потом math,
 * потом словарь уровнями (Duolingo-путь): level ASC, внутри уровня added ASC.
 * Вынесено из buildQueue, потому что тем же порядком урок добирает лишнее новое слово,
 * когда иначе ему нечего показать (см. Review.tsx::proceed).
 */
export function freshItems(items: StudyItem[]): StudyItem[] {
  return items
    .filter(i => i.fsrs.state === State.New)
    .sort((a, b) => {
      const ka = kindRank(a.view)
      const kb = kindRank(b.view)
      if (ka !== kb) return ka - kb
      if (isLevelled(a.view) && isLevelled(b.view)) {
        if (a.view.level !== b.view.level) return a.view.level - b.view.level
        const ad = a.view.added.localeCompare(b.view.added)
        if (ad !== 0) return ad
        return a.view.slug.localeCompare(b.view.slug)
      }
      const ad = b.view.added.localeCompare(a.view.added)
      if (ad !== 0) return ad
      return a.view.slug.localeCompare(b.view.slug)
    })
}

/**
 * Следующие новые слова за пределами урочного лимита — последняя ступень добора (B4).
 * После NEW_STOP_DATE добора нет: этот путь (bonusNew в Review.tsx) — второй вход
 * нового слова в урок, помимо основного бюджета buildQueue, и обязан закрываться тем же
 * правилом, иначе «стоп ввода» держится наполовину.
 */
export function nextNewItems(cards: CardView[], exclude: Set<string>, limit = 1, now: Date = new Date()): StudyItem[] {
  if (!newIntroAllowed(now)) return []
  return freshItems(expandItems(cards, now))
    .filter(i => i.skill === 'recall' && !exclude.has(itemKey(i)))
    .slice(0, Math.max(0, limit))
}

/**
 * Очередь сессии: Learning/Relearning → Review (due сегодня) → New (лимит).
 * Review и New перемешаны interleaving-ом, learning — впереди по due.
 */
export function buildQueue(cards: CardView[], newBudget: number, now: Date = new Date(), forced?: Set<string>): StudyItem[] {
  const eod = endOfStudyDay(now)
  const items = expandItems(cards, now)

  const learning = items
    .filter(i => isLearning(i.fsrs.state) && i.fsrs.due.getTime() <= now.getTime() + LEARN_AHEAD_MS)
    .sort((a, b) => a.fsrs.due.getTime() - b.fsrs.due.getTime())

  /* Потолок повторов за урок. Его не было вовсе: очередь брала ВСЁ, что
     просрочено, без ограничения.

     Пока живых карточек 38, это не видно. На четырёхстах словах и нынешней
     медиане стабильности выходит порядка 160 повторов в день, а пропуск
     недели даёт больше тысячи — часа два одним куском. Такой урок не
     начинают, долг растёт дальше, и колода умирает не от сложности, а от
     размера очереди.

     Самое просроченное идёт первым: чем дольше карточка ждёт, тем ближе она к
     полному забыванию. Остаток вернётся следующим уроком — в отличие от
     двухчасовой стены, которую просто закрывают. */
  const overdue = items
    .filter(i => i.fsrs.state === State.Review && i.fsrs.due.getTime() < eod.getTime())
    .sort((a, b) => a.fsrs.due.getTime() - b.fsrs.due.getTime())
  /* Урочный и дневной потолки решают разные задачи, поэтому их два.
     Урочный (MAX_REVIEW_PER_LESSON) — про длину одного захода: 60 повторов ≈
     12–15 минут, урок такой длины начинают. Дневной (MAX_REVIEW_PER_DAY) — про
     сутки целиком: без него второй урок выдавал ещё до 60 повторов, третий ещё,
     и защиты от лавины просрочки на уровне дня не было вовсе. */
  const review = shuffle(overdue.slice(0, Math.min(MAX_REVIEW_PER_LESSON, reviewsLeftToday(items, now))))

  // выбор новых: сначала error/grammar (закрывают доказанные пробелы), потом pt-разбор, потом
  // math, потом словарь; словарь идёт уровнями (Duolingo-путь): level ASC, внутри уровня —
  // свежедобавленные последними (added ASC, стабильный порядок). error/grammar/math/transition —
  // порядок прежний: added DESC.
  // NEW_STOP_DATE: после стопа бюджет нулевой независимо от того, что передал вызывающий —
  // правило живёт здесь, а не в каждом месте, которое считает newBudget снаружи.
  const fresh = freshItems(items)
  const effectiveBudget = newIntroAllowed(now) ? newBudget : 0
  const newItems = shuffle(fresh.slice(0, Math.max(0, effectiveBudget)))

  // interleaving с разрядкой: новые распределяем среди review, но не ближе чем через
  // NEW_GAP других карточек; позицию 0 не занимаем — сессия начинается с повтора, если он есть.
  // Если повторов мало и слова всё равно встают рядом, очередь дополнительно разряжается
  // на лету (отработка только что введённого слова служит разделителем).
  const mixed: StudyItem[] = [...review]
  if (newItems.length) {
    const stride = Math.max(NEW_GAP + 1, Math.round((review.length + newItems.length) / newItems.length))
    newItems.forEach((it, i) => {
      const pos = Math.min(mixed.length, (review.length ? 1 : 0) + i * stride)
      mixed.splice(pos, 0, it)
    })
  }

  // point 3: обязательный добор. Слова, введённые сегодня и ещё не отработанные в двух
  // последующих сессиях (список forced считает вызывающий по журналу), принудительно
  // попадают в урок — даже если их due перенесён на завтра (см. point 1, держим в Learning).
  // Берём только recall-единицы в Learning/Relearning: New уже в пуле новых, Review-слова
  // (напр. «уже знаю это слово») отработки не требуют. Добор — в хвост, перемешанный.
  const already = new Set([...learning, ...review, ...newItems].map(itemKey))
  const drills = forced?.size
    ? shuffle(items.filter(i =>
        i.skill === 'recall' && forced.has(i.view.slug) && isLearning(i.fsrs.state) && !already.has(itemKey(i))))
    : []
  return [...learning, ...mixed, ...drills]
}

/**
 * Заполнитель (B4, третья ступень лестницы добора): повтор, срок которого ещё не пришёл,
 * но придёт в ближайшие трое суток. Нужен, когда урок обязан развести знакомство и первую отработку
 * слова (A3), а разбавлять нечем: после большой сессии всё введённое уезжает на следующий день
 * (A1), пул созревших пустеет, и урок вырождался в одно знакомство. Ранний повтор — правка
 * состава очереди, не формул: FSRS штатно обрабатывает досрочный показ (E1 не нарушается).
 * Ступень включается ТОЛЬКО когда без неё урок встанет, и ограничена MAX_EARLY_FILLERS,
 * чтобы не вычерпывать завтрашний день.
 */
export const FILLER_LOOKAHEAD_MS = 72 * 3600_000
export const MAX_EARLY_FILLERS = 12

/**
 * Насколько урок может превысить свой лимит новых слов, когда иначе ему нечего показать.
 * Урочный лимит — про комфортный темп, и он уступает пустому экрану, но не безгранично:
 * без потолка урок на тонком пуле вводил всю дневную норму за один присест.
 * Дневной лимит (norms.ts::NEW_PER_DAY) не превышается никогда.
 */
export const MAX_INTRO_BONUS = 2

export function earlyFillers(cards: CardView[], now: Date, exclude: Set<string>, limit = MAX_EARLY_FILLERS): StudyItem[] {
  const eod = endOfStudyDay(now)
  const horizon = now.getTime() + FILLER_LOOKAHEAD_MS
  const сегодня = dayKey(now)
  return expandItems(cards, now)
    .filter(i => {
      if (i.fsrs.state === State.New) return false
      /* Спрошенное сегодня в заполнители не берём. Память «что уже показано» жила
         внутри урока (`drilled` в экране), а лестница добора смотрит на трое суток
         вперёд — и второй урок того же вечера начинался с той же карточки: ответив
         на неё, ученик сам сделал её ближайшей по сроку, а заполнители сортируются
         именно по сроку. Замер 20.08.2026: 51 показ на 27 карточек за день.
         Обязательная отработка введённого сегодня слова (`forcedTodaySlugs`) от
         этого не страдает — она идёт своей дорогой, через buildQueue. */
      if (i.fsrs.last_review && dayKey(i.fsrs.last_review) === сегодня) return false
      const t = i.fsrs.due.getTime()
      // уже созревшее в заполнители не берём — оно и так попадает в очередь обычным путём
      const readyNow = isLearning(i.fsrs.state) ? t <= now.getTime() + LEARN_AHEAD_MS : t < eod.getTime()
      return !readyNow && t <= horizon && !exclude.has(itemKey(i))
    })
    .sort((a, b) => a.fsrs.due.getTime() - b.fsrs.due.getTime())
    .slice(0, Math.max(0, limit))
}

/**
 * Возврат карточки в очередь после оценки: позиция пропорциональна времени до
 * due (~20 c на карточку), иначе 10-минутный learning-шаг схлопнулся бы в
 * полминуты и слово «выучивалось» бы из рабочей памяти, минуя интервал.
 *
 * Так и происходило. Прежняя версия зажимала позицию в `Math.min(queueLen, …)`
 * — то есть при короткой очереди ставила карточку в конец и возвращала её
 * через минуту вместо десяти. А очередь короткая почти всегда: новых за урок
 * было три, повторов у молодой колоды мало.
 *
 * Что это сделало с моделью, по живым данным за две недели: 472 отработки на
 * 49 уникальных слов, 3.21 показа слова за день, две трети промежутков между
 * показами одного слова — меньше получаса. Медиана difficulty 9.08 из 10,
 * медиана стабильности 1.25 дня, зрелых карточек НОЛЬ, ни одно слово не вышло
 * за интервал в десять дней. Модель считала, что слово забывается за часы, —
 * потому что её и спрашивали каждые несколько минут.
 *
 * Теперь честно: не помещается — не возвращаем. Карточка уходит из урока со
 * своим настоящим сроком и приходит следующим заходом. Пустой урок лучше
 * испорченной модели.
 */
export function requeuePosition(queueLen: number, next: FsrsCard, now: Date): number | null {
  const waitMs = next.due.getTime() - now.getTime()
  const нужно = Math.max(3, Math.ceil(waitMs / 20000))
  return нужно <= queueLen ? нужно : null
}

export function shouldRequeue(next: FsrsCard, now: Date): boolean {
  return isLearning(next.state) && next.due.getTime() - now.getTime() < 30 * 60000
}

/**
 * Последняя ступень лестницы обучения: с неё верный ответ выпускает карточку в
 * Review, а с любой другой означает «ещё десять минут». Берётся из тех же
 * параметров FSRS, что и планировщик, — иначе смена лестницы в настройках
 * разошлась бы с отсрочкой выпуска молча.
 */
export const LAST_LEARNING_STEP = Math.max(0, generatorParameters({}).learning_steps.length - 1)

/**
 * Слово, введённое сегодня, не уходит в Review внутри того же учебного дня
 * (point 1). Три верных ответа за минуту проверяют кратковременный буфер, а не
 * долговременную память: stability такой карточки завышена и знания не
 * отражает. Держим её в Learning до следующего календарного дня — due на конец
 * учебного дня (rollover 04:00), настоящий выпуск будет завтра, когда
 * `introDay` перестанет совпадать с сегодняшним днём.
 *
 * КАРТОЧКА ПАРКУЕТСЯ НА ПОСЛЕДНЕЙ СТУПЕНИ ОБУЧЕНИЯ. FSRS отдаёт выпущенную
 * карточку с `learning_steps = 0`, и раньше этот ноль уезжал в файл вместе с
 * возвращённым состоянием — карточка падала на низ лестницы, хотя выпуск уже
 * заслужила. Следующий Good поднимал её лишь на ступень «через 10 минут», то
 * есть возвращал в тот же урок и в следующий, а не откладывал до завтра.
 * Замер 21.08.2026 по журналу: карточка разбора с тремя Good подряд так и
 * осталась в Learning и приходила каждые десять минут пять часов подряд —
 * жалоба «одни и те же два примера крутятся и крутятся».
 *
 * Правка того же дня сохраняла `prev.learning_steps`, и этого мало: ступень
 * «перед оценкой» равна последней только тогда, когда выпуск пришёл с
 * последней ступени. Easy выпускает карточку с любой, в том числе с нулевой, —
 * и отложенная карточка снова оказывалась на рунг ниже заслуженного. Инвариант
 * здесь ровно один: выпуск заслужен и отложен до завтра, значит ОДИН верный
 * ответ завтра обязан выпустить карточку. Его и выражает последняя ступень, а
 * не та, с которой карточка пришла.
 *
 * Функция чистая и живёт здесь, а не внутри `rateItem`, чтобы её можно было
 * проверить настоящей последовательностью оценок из журнала.
 */
export function holdOnIntroDay(prev: FsrsCard, next: FsrsCard, now: Date, introDay: string | null): FsrsCard {
  const wasIntro = prev.state === State.New || prev.state === State.Learning || prev.state === State.Relearning
  if (!(next.state === State.Review && wasIntro && introDay && introDay === dayKey(now))) return next
  const nextDay = endOfStudyDay(now)
  return {
    ...next,
    state: State.Learning,
    learning_steps: LAST_LEARNING_STEP,
    due: nextDay,
    scheduled_days: Math.max(1, Math.round((nextDay.getTime() - now.getTime()) / 86400_000))
  }
}

/**
 * Формат упражнения:
 * - prep-навык → всегда prep (выбор предлога);
 * - recall в New → intro (знакомство: слово+значения+пример, без викторины);
 * - recall в Learning/Relearning → reveal (retrieval уже возможен — слово показывали);
 * - recall в Review → чередование по reps: MC (формат Words in Context цифрового SAT,
 *   дистракторы из колоды) и ввод с клавиатуры (production + написание).
 */
/**
 * Формат показа.
 *
 * C8 (17.08.2026). До этой даты словарь в Review проверялся ОДНИМ способом —
 * выбором слова из четырёх в пропуске предложения. Правка 05.08 сделала MC
 * основным форматом (обоснованно: `type` занимал 271 показ из 472, а SAT
 * проверяет словарь рецептивно), но `mcReady()` истинно почти всегда, поэтому
 * «основной» на практике означало «единственный», а ввод остался за выключенным
 * по умолчанию тумблером.
 *
 * Что из этого вышло, словами самого Александра 17.08.2026: «где выбор из 4 слов
 * я просто выбираю знакомое, а в предложениях вижу знакомое предложение и помню,
 * какое слово там было». Обе лазейки — прямое следствие конструкции, а не лени:
 * у слова три фиксированных контекста, значит на десяти повторах каждое
 * предложение возвращается трижды, а выбор из четырёх слов вознаграждает
 * узнавание формы, а не знание значения.
 *
 * Поэтому Review идёт по ротации `REVIEW_CYCLE`: два режима из четырёх не
 * показывают предложение вовсе (заучивать нечего), один спрашивает обратное
 * направление русскими значениями (знакомость английского слова не помогает), и
 * один требует произвести слово по памяти (угадывать не из чего).
 *
 * Прежний запрет ввода снят сознательно: он держался на двух основаниях, и оба
 * отпали — рука Александра зажила (подтверждено 17.08.2026), а в ротации `type`
 * даёт четверть показов вместо прежних 57%. Тумблер `typing` остаётся, но теперь
 * включён по умолчанию и означает «участвует ли ввод в ротации».
 */
export function pickFormat(item: StudyItem, deck: CardView[], introduced?: Set<string>, lapsed?: Set<string>, reintroAllowed = true, typing = false): Format {
  return pickTask(item, deck, introduced, lapsed, reintroAllowed, typing).format
}

/** По чему вспоминаем: пропуск в предложении, значение (ответ — слово) или слово (ответ — значение). */
export type Cue = 'sentence' | 'meaning' | 'word'

/**
 * Ротация режимов проверки в Review, по числу оценок карточки.
 *
 * Порядок не случаен: первым идёт формат реального экзамена, чтобы он оставался
 * тренируемым, дальше — режимы, закрывающие лазейки. Шаг, недоступный карточке
 * (нет значения, мало дистракторов, ввод выключен), деградирует к ближайшему
 * возможному, а не пропускается: пропуск сдвинул бы фазу и вернул предложение в
 * каждый показ.
 */
/* С какого повтора карточка попадает в ротацию. Два — это «слово уже дважды
   опознано»: тот же порог, что у C1 для производства (см. baseFormat). */
export const ROTATE_FROM_REPS = 2

export const REVIEW_CYCLE: ReadonlyArray<{ format: Format; cue: Cue }> = [
  { format: 'mc', cue: 'sentence' },  // Words in Context — целевой формат SAT
  { format: 'mc', cue: 'meaning' },   // значение → слово, предложения нет
  { format: 'mc', cue: 'word' },      // слово → значение, варианты по-русски
  { format: 'type', cue: 'meaning' }, // значение → вписать слово (производство)
]

/* Окончания русских слов — от длинных к коротким (порядок задаёт сортировка, а не
   рука: перепутанный вручную список молча срезал бы «ать» там, где надо «ывать»).
   Список закрытый и намеренно короткий: глоссы колоды пишет человек в словарной
   форме — инфинитив, прилагательное, отглагольное существительное, — и полная
   морфология здесь не нужна. Буква «ё» до основы не доживает (см. stemRu), поэтому
   «ённый» в списке нет — только «енный». */
const RU_ENDINGS: readonly string[] = [
  'ированием', 'ированию', 'ирования', 'ирование',
  'ениями', 'аниями', 'остями', 'остей', 'остям', 'остях',
  'ениям', 'аниям', 'ениях', 'аниях', 'ением', 'анием',
  'ающий', 'ующий', 'ивший', 'ывший', 'енный', 'анный', 'янный',
  'ающая', 'ующая', 'ающее', 'ующее', 'ность', 'остью',
  'ывать', 'ивать', 'овать', 'евать', 'ыми', 'ими', 'его', 'ого', 'ему', 'ому',
  'ение', 'ание', 'ения', 'ании', 'аний', 'ений', 'ению', 'анию', 'ость', 'ости',
  'ный', 'ная', 'ное', 'ные', 'ных', 'ным', 'ной', 'ную',
  'ать', 'ять', 'ить', 'еть', 'уть', 'ыть',
  'ами', 'ями', 'ах', 'ях', 'ам', 'ям', 'ов', 'ев',
  'ий', 'ый', 'ой', 'ая', 'ое', 'ые', 'ым', 'ых', 'ую', 'юю', 'ею', 'ою',
  'ем', 'им', 'ом', 'их', 'ка', 'ки', 'ке', 'ку', 'ть', 'ти', 'чь',
  'а', 'я', 'о', 'е', 'у', 'ю', 'ы', 'и', 'ь', 'й'
].slice().sort((a, b) => b.length - a.length)

/* Сколько букв обязано остаться в основе. Четыре — не круглое число: при трёх
   «срок» превращается в «ср», а «мера» и «мерить» слипаются с половиной словаря. */
const RU_STEM_MIN = 4

/* Служебные слова: сами значения не несут, но стоят в куске первыми и заслонили бы
   главное слово («в силе», «по видимости»). Отрицания здесь нет намеренно — см. RU_NEGATION. */
const RU_STOP: ReadonlySet<string> = new Set([
  'в', 'во', 'на', 'о', 'об', 'обо', 'по', 'к', 'ко', 'с', 'со', 'из', 'от', 'до',
  'для', 'при', 'под', 'над', 'за', 'у', 'и', 'а', 'но', 'или', 'либо', 'то', 'же',
  'бы', 'ли', 'что', 'чтобы', 'как', 'так', 'это', 'этот', 'эта', 'тот', 'та', 'те',
  'все', 'весь', 'вся', 'более', 'менее', 'очень', 'лишь', 'только', 'даже', 'еще',
  'уже', 'когда', 'где', 'чем', 'его', 'ее', 'их', 'ему', 'ей', 'им', 'ими', 'кто',
  'сам', 'сама', 'само', 'себя', 'себе', 'т', 'ч', 'др', 'пр'
])

/* Слова, которые в глоссе значения не несут, пока за ними стоит что-то ещё.
   «ставить под угрозу» (compromise) и «ставить под сомнение» (contest) — разные
   значения, и по общему «ставить» правило объявило бы их двойниками; то же с
   «давать оценку»/«давать возможность» и «постепенно ухудшаться»/«постепенно
   видоизменяться». Смысл в таких оборотах несёт дополнение, а не глагол-связка и
   не наречие. Если же связка — единственное содержательное слово куска
   («производить»), она и есть значение: список пропускает её вперёд, а не
   вычёркивает (см. glossKey). */
const RU_LIGHT: ReadonlySet<string> = new Set([
  'делать', 'сделать', 'давать', 'дать', 'приводить', 'привести', 'ставить',
  'поставить', 'вызывать', 'вызвать', 'вызывающий', 'иметь', 'быть', 'являться',
  'становиться', 'стать', 'оказывать', 'оказать', 'брать', 'взять', 'держать',
  'служить', 'испытывать', 'испытывающий', 'представлять', 'представить',
  'приходить', 'прийти', 'носить', 'придавать',
  'прямо', 'постепенно', 'полностью', 'частично', 'слегка', 'сильно', 'резко',
  'явно', 'обычно', 'особенно', 'крайне', 'чрезмерно', 'намеренно', 'заведомо',
  'вполне', 'довольно', 'нередко', 'часто', 'иногда', 'всегда', 'никогда',
  'снова', 'заново', 'вновь', 'сразу', 'наконец', 'вообще', 'скорее'
])

/* Отрицание — часть значения, а не служебное слово. «не обоснованный правилом»
   (arbitrary) и «обосновывать» (justify) — антонимы; сними «не», и правило объявит
   их двойниками, выбросив лучший дистрактор друг к другу. Поэтому отрицание
   остаётся в ключе приставкой «не-». */
const RU_NEGATION: ReadonlySet<string> = new Set(['не', 'без', 'ни'])

/**
 * Основа русского слова: «укреплять», «укрепление», «укреплённый» → «укрепл».
 *
 * Отсекаются ТОЛЬКО окончания. Приставка неприкосновенна: на ней держится разница
 * между «сходиться» и «расходиться», «утверждать» и «подтверждать» — то есть ровно
 * между антонимами и между разными словами колоды.
 */
export function stemRu(word: string): string {
  let w = word.toLowerCase().replace(/ё/g, 'е')
  // возвратность снимается первой: «сходиться» → «сходить» → «сход»
  if (w.length - 2 > RU_STEM_MIN && (w.endsWith('ся') || w.endsWith('сь'))) w = w.slice(0, -2)
  for (const end of RU_ENDINGS) {
    if (w.endsWith(end) && w.length - end.length >= RU_STEM_MIN) { w = w.slice(0, -end.length); break }
  }
  // мягкий знак на срезе — след окончания, а не основы: «произвольный» → «произволь» → «произвол»
  const без = w.replace(/[ьъ]$/, '')
  return без.length >= 3 ? без : w
}

/**
 * Ключ куска значения — основа его ГЛАВНОГО слова: «укреплять уже имеющееся» → «укрепл».
 *
 * Кусок целиком ключом быть не может, и это не мелочь стиля. Замер 22.08.2026 по живой
 * колоде: `reinforce` («усиливать, укреплять уже имеющееся») и `buttress` («подкреплять,
 * укреплять») посимвольно не совпадают ни одним куском, хотя «укреплять» стоит у обоих;
 * `corroborate` («подтверждать независимым источником») — один длинный кусок, не
 * совпадающий вообще ни с чем. Уточнение после главного слова («уже имеющееся»,
 * «независимым источником») — это оттенок употребления, а не другое значение.
 */
function glossKey(part: string): string {
  let negated = false
  let связка = ''   // связка из RU_LIGHT: годится в ключ, только если содержательных слов больше нет
  for (const token of part.split(/[^а-яa-z0-9-]+/i)) {
    if (!token) continue
    if (RU_NEGATION.has(token)) { negated = true; continue }
    if (RU_STOP.has(token)) continue
    const stem = stemRu(token)
    if (stem.length < 3) continue
    if (RU_LIGHT.has(token)) { связка ||= (negated ? 'не-' : '') + stem; continue }
    return (negated ? 'не-' : '') + stem
  }
  return связка
}

/**
 * Значения карточки как множество ключей: «облегчать, способствовать» → {облегч, способств}.
 *
 * Пояснения в скобках выбрасываются: «расходиться (о путях, мнениях)» — это не
 * значение, а пример употребления. По ним слова совпадают ложно: converge и
 * diverge — антонимы, но «мнениях» стоит у обоих, и без этой чистки правило
 * выбросило бы лучший дистрактор к слову вместо худшего.
 */
function glossParts(v: CardView): Set<string> {
  const out = new Set<string>()
  for (const part of (v.meaning_ru || '').toLowerCase().replace(/\([^)]*\)/g, ' ').split(/[,;/]| или /)) {
    const key = glossKey(part)
    if (key) out.add(key)
  }
  return out
}

/**
 * Двойник по значению — слово, которое в том же предложении тоже верно.
 *
 * C9: такое слово не может быть дистрактором. «The new protocol was meant to
 * ______ collaboration between the two labs» с вариантами facilitate и foster
 * не имеет одного верного ответа: foster collaboration — обычное английское
 * сочетание, и ученик, выбравший его, получает «мимо» за верный ответ.
 *
 * Признак — общая ОСНОВА куска русского значения плюс одна часть речи.
 *
 * Основа, а не кусок целиком: посимвольное сравнение видело двойника только там,
 * где тьютор дословно повторил формулировку, и слепло на «укреплять» против
 * «укреплять уже имеющееся» (см. glossKey). Замеры по живой колоде, 400 словарных
 * карточек (kind vocab, pos ≠ transition): было 87 пар и 128 карточек (32%), стало
 * 210 пар и 231 карточка (58%).
 *
 * Часть речи: слово другой части речи в тот же пропуск не встаёт — вторым верным
 * вариантом оно быть не может, и введённым синонимом тоже. Проверено: из прежних
 * 87 пар разночастеречных НОЛЬ, то есть требование ничего не отнимает у старого
 * поведения, а у нового снимает 56 пар шума вроде acute/embody и apt/ascertain.
 *
 * Цена ошибки здесь несимметрична, и правило сдвинуто в сторону дешёвой: лишний
 * двойник стоит одного дистрактора из пула в сотни слов (замер после правки:
 * карточек, которым не хватило трёх дистракторов, — ноль), пропущенный двойник
 * стоит второго верного варианта в задании.
 *
 * Авторские ловушки тьютора проверяются тем же правилом, а не берутся на веру:
 * ловушка, которая тоже верна, — не ловушка. Ловушки по написанию (facilitate /
 * felicitate) значений не делят и проверку проходят.
 */
export function meaningTwin(card: CardView): (other: CardView) => boolean {
  const parts = glossParts(card)
  if (!parts.size) return () => false
  return other => {
    if (other.pos !== card.pos) return false
    for (const p of glossParts(other)) if (parts.has(p)) return true
    return false
  }
}

/** Тот же вопрос про одну пару — для тестов и вызовов вне выборки дистракторов. */
export function sharesMeaning(a: CardView, b: CardView): boolean {
  return meaningTwin(a)(b)
}

/**
 * Дистракторы-значения для обратного режима (`cue: 'word'`).
 *
 * Здесь узнавание по новизне не работает в принципе — все варианты русские, — но
 * работает семантическая далёкость: если значения из разных смысловых зон, ответ
 * виден без знания слова. Поэтому лестница ведёт от самых похожих (та же часть
 * речи и та же ступень) к любым словам раздела.
 */
export function meaningDistractors(card: CardView, deck: CardView[], n = 3): string[] {
  const answer = (card.meaning_ru || '').trim()
  const taken = new Set([answer.toLowerCase()])
  const sec = sectionOf(card)
  // C9: значение-двойник среди вариантов делает верными сразу два (см. meaningTwin)
  const двойник = meaningTwin(card)
  const pool = deck.filter(c =>
    !c.suspended && c.path !== card.path && sectionOf(c) === sec && !!(c.meaning_ru || '').trim() &&
    !двойник(c))
  const samePos = (c: CardView) => c.pos === card.pos
  // 999 — «без уровня» (связки, SEC): такие между собой не роднее, чем любые другие
  const sameLevel = (c: CardView) => card.level !== 999 && c.level === card.level
  const ladder: CardView[][] = [
    pool.filter(c => samePos(c) && sameLevel(c)),
    pool.filter(samePos),
    pool
  ]
  const out: string[] = []
  for (const step of ladder) {
    if (out.length >= n) break
    for (const c of shuffle(step)) {
      if (out.length >= n) break
      const m = (c.meaning_ru || '').trim()
      if (taken.has(m.toLowerCase())) continue
      out.push(m)
      taken.add(m.toLowerCase())
    }
  }
  return out.slice(0, n)
}

/** Формат и цель показа вместе: Review.tsx рисует по паре, тесты проверяют пару. */
export function pickTask(item: StudyItem, deck: CardView[], introduced?: Set<string>, lapsed?: Set<string>, reintroAllowed = true, typing = false): { format: Format; cue: Cue } {
  const format = baseFormat(item, deck, introduced, lapsed, reintroAllowed, typing)
  if (format !== 'mc' && format !== 'type') return { format, cue: 'sentence' }
  // авторские варианты (error/grammar) и числовой ответ (math) — своя механика, ротации нет
  if (item.view.choices.length >= 2 || item.view.answerNum) return { format, cue: 'sentence' }
  /* Ротацию открывает второй повтор, а не переход в Review.
     Раньше здесь стояло только `state !== Review`, и на выросшей колоде это
     молча выключило производство. В learning `baseFormat` отдаёт mc, пока в
     колоде находятся три дистрактора, — а находятся они всегда, — так что
     ветка `type` внизу baseFormat достижима лишь на крошечной колоде.
     Замер журнала: в июле, пока колода была мала, 274 показа вводом; 20.08 —
     три, и все три у карточек в Review. Слово, застрявшее в learning, ученик
     десять раз узнавал среди четырёх вариантов и ни разу не вспоминал сам —
     ровно эти слова и оказались пиявками. Узнавание с подсказкой не готовит к
     экзамену, где подсказки нет. */
  if (item.fsrs.state !== State.Review && item.fsrs.reps < ROTATE_FROM_REPS) return { format, cue: 'sentence' }
  const step = REVIEW_CYCLE[((item.fsrs.reps % REVIEW_CYCLE.length) + REVIEW_CYCLE.length) % REVIEW_CYCLE.length]
  return degrade(step, item, deck, typing)
}

/**
 * Ближайший исполнимый режим, если выпавший шаг карточке недоступен.
 * Порядок отката: word → meaning → sentence; type → mc с тем же cue.
 */
function degrade(step: { format: Format; cue: Cue }, item: StudyItem, deck: CardView[], typing: boolean): { format: Format; cue: Cue } {
  const view = item.view
  const hasMeaning = !!(view.meaning_ru || '').trim()
  const canProduce = !view.word.includes(' ') && hasMeaningHint(view)
  let cue = step.cue
  if ((cue === 'meaning' || cue === 'word') && !hasMeaning) cue = 'sentence'
  if (cue === 'word' && meaningDistractors(view, deck).length < 3) cue = 'meaning'
  let format = step.format
  if (format === 'type' && !(typing && canProduce)) format = 'mc'
  // выбор слова требует трёх словесных дистракторов; без них остаётся показ
  if (format === 'mc' && cue !== 'word' && mcDistractors(view, deck).length < 3) {
    return typing && canProduce ? { format: 'type', cue: hasMeaning ? 'meaning' : 'sentence' } : { format: 'reveal', cue }
  }
  return { format, cue }
}

function baseFormat(item: StudyItem, deck: CardView[], introduced?: Set<string>, lapsed?: Set<string>, reintroAllowed = true, typing = false): Format {
  if (item.skill === 'prep') return 'prep'
  // авторские варианты (error/grammar/math) — всегда MC, включая первый показ
  if (item.view.choices.length >= 2) return 'mc'
  // числовой ответ (math) — всегда ввод, включая первый показ
  if (item.view.answerNum) return 'type'
  const typable = !item.view.word.includes(' ')
  // C5: ввод по буквам допустим только при однозначном ответе — слово из одного токена И есть
  // подсказка значения. Без значения задание по контексту неоднозначно (синонимы) — тогда reveal/mc.
  const canProduce = typable && hasMeaningHint(item.view)
  const mcReady = () => mcDistractors(item.view, deck).length >= 3
  if (item.fsrs.state === State.New) {
    // знакомство один раз за сессию; после него первая отработка — узнавание
    return introduced?.has(itemKey(item)) ? (mcReady() ? 'mc' : 'reveal') : 'intro'
  }
  // слово, которое не смогли вспомнить («Заново» в этой сессии — на ЛЮБОЙ стадии, не только Review;
  // либо пришедшее в Relearning из прошлой сессии) — один раз переznakomим окном-знакомством
  // (значение + пример), в UI подпись «Подзабылось» вместо «Новое слово». Но окно-переznakomство
  // тратит тот же урочный лимит, что и новые (для мозга «Подзабылось» — та же нагрузка знакомства):
  // сверх лимита провал отрабатывается обычным упражнением, без окна.
  const failed = lapsed?.has(itemKey(item)) || (item.fsrs.state === State.Relearning && !introduced?.has(itemKey(item)))
  if (failed && reintroAllowed) return 'intro'
  if (item.fsrs.state !== State.Review) {
    // C1: производство (type) — не раньше, чем слово дважды опознано (reveal/mc). reps считает
    // реальные оценки (intro рейтинга не даёт), поэтому reps>=2 = после двух опознаний. Написание
    // по буквам через минуту после первого показа — гарантированный провал (scrutinize/bolster/
    // corroborate 17.07 застряли на type со stability 0.01). Выпускной шаг — объективный формат:
    // самооценка склонна к «показалось знакомым». C5: type — только если ответ однозначен (canProduce).
    if (mcReady()) return 'mc'
    return typing && item.fsrs.reps >= 2 && canProduce ? 'type' : 'reveal'
  }
  if (mcReady()) return 'mc'
  // C5: без подсказки значения ввод неоднозначен — тогда reveal (показ), но не type
  return typing && canProduce ? 'type' : 'reveal'
}

/**
 * C5: задание на ввод (`type`) обязано иметь однозначный ответ. Для словарной карточки это
 * значит, что дана подсказка значения (`meaning_ru`/`meaning_en`) — иначе «a ___ toward positive
 * results» допускает bias/tendency/skew, и верный по смыслу ответ засчитается провалом. Числовой
 * ответ (math) однозначен сам по себе и проверяется раньше, до вызова этого предиката.
 */
export function hasMeaningHint(v: CardView): boolean {
  return !!(v.meaning_ru || v.meaning_en)
}

/** Слово уже показывали и оценивали: reps растёт только с оценкой (A7 — intro знакомством не считается) */
export function isSeenWord(v: CardView): boolean {
  return v.fsrs.reps > 0 || v.fsrs.state !== State.New
}

/**
 * Дистракторы для MC.
 *
 * C6: варианты берутся из слов, которые ученик уже видел. Иначе задание решается
 * узнаванием новизны, а не значением: 06.08.2026 Александр сформулировал это сам —
 * «при выборе слов я просто выбираю знакомое». Замер того же дня: оценку хоть раз
 * получили 49 слов из 450, то есть случайный дистрактор из колоды с вероятностью
 * ~89% ученику вообще не показывался, и правильный ответ отличим не читая
 * предложение. Точность mc 42/47 при этом не измеряла ничего.
 */
export function mcDistractors(card: CardView, deck: CardView[], n = 3): string[] {
  /* Раньше здесь стояло `if (authored.length >= n) return authored` — и это
     вырождало упражнение.
     Замер на живой колоде: confusables ровно по три у 415 карточек из 450.
     Значит четвёрка вариантов у почти каждого слова была зафиксирована
     НАВСЕГДА, менялся только порядок, а ветка выбора по части речи была
     достижима у 35 карточек. Хуже: из 1245 авторских дистракторов лишь 358
     (29%) сами есть в колоде — остальные не встречаются больше нигде, и через
     два показа задание вырождается в «выбери знакомое слово среди трёх
     незнакомых». Узнавание по новизне, а не по значению.

     Теперь пул пересобирается на каждом показе: один авторский дистрактор
     (самая острая ловушка тьютора — их и проверяет SAT) плюс живые слова той же
     части речи из того же раздела. Тьюторская разметка не выбрасывается, но
     перестаёт быть единственным источником. */
  const AUTHORED_KEEP = 1
  const sec = sectionOf(card)
  const taken = new Set([card.word.toLowerCase()])
  const двойник = meaningTwin(card)   // C9: слово-двойник тоже верно в этом предложении
  const pool = deck.filter(c =>
    !c.suspended && c.word.toLowerCase() !== card.word.toLowerCase() && sectionOf(c) === sec &&
    !двойник(c))
  const seenWords = new Set(pool.filter(isSeenWord).map(c => c.word.toLowerCase()))
  /* Авторский дистрактор тоже проверяется на знакомость: 71% confusables не
     встречаются в колоде больше нигде, и незнакомая ловушка выдаёт ответ ровно так же,
     как незнакомый случайный сосед. Знакомые авторские идут первыми, незнакомые
     остаются в хвосте — как запас, когда живых слов не хватает. */
  const двойникПоСловарю = (w: string) => {
    const c = deck.find(x => x.word.toLowerCase() === w.toLowerCase())
    return !!c && двойник(c)
  }
  const authored = shuffle(card.confusables.filter(c =>
    c && c.toLowerCase() !== card.word.toLowerCase() && !двойникПоСловарю(c)))
    .sort((a, b) => Number(seenWords.has(b.toLowerCase())) - Number(seenWords.has(a.toLowerCase())))
  const out: string[] = []
  for (const a of authored.slice(0, AUTHORED_KEEP)) {
    if (!seenWords.has(a.toLowerCase())) break // незнакомую ловушку берём только в добор, ниже
    out.push(a)
    taken.add(a.toLowerCase())
  }
  /* Лестница источников: знакомое той же части речи → любое знакомое раздела →
     незнакомое той же части речи → любое слово раздела. Незнакомые ступени —
     страховка для первых недель, пока видённых слов меньше четырёх на раздел;
     как только пул набирается, они недостижимы. */
  const samePos = (c: CardView) => c.pos === card.pos
  const ladder: CardView[][] = [
    pool.filter(c => isSeenWord(c) && samePos(c)),
    pool.filter(isSeenWord),
    pool.filter(samePos),
    pool
  ]
  for (const step of ladder) {
    if (out.length >= n) break
    for (const w of shuffle(step.map(c => c.word))) {
      if (out.length >= n) break
      if (taken.has(w.toLowerCase())) continue
      out.push(w)
      taken.add(w.toLowerCase())
    }
  }
  // колода мала или раздел почти пуст — добираем оставшимися авторскими
  for (const a of authored) {
    if (out.length >= n) break
    if (taken.has(a.toLowerCase())) continue
    out.push(a)
    taken.add(a.toLowerCase())
  }
  return out.slice(0, n)
}

/**
 * C7: следующий пример карточки. Ротация обязана переживать перезапуск приложения.
 *
 * Раньше индекс жил в Map внутри модуля экрана и обнулялся при каждом открытии PWA,
 * а карточка внутри урока показывается один раз в 140 случаях из 262 (журнал на
 * 06.08.2026) — то есть почти каждый показ приходился на contexts[0], и слово
 * заучивалось вместе с единственным предложением.
 *
 * `last` — сохранённый индекс прошлого показа (null, если приложение только открыли);
 * тогда счётчиком служит число оценок карточки: оно переживает не только перезапуск,
 * но и переустановку — reps приходит из frontmatter карточки в репозитории.
 */
export function nextCtxIndex(last: number | null | undefined, reps: number, len: number): number {
  if (len <= 1) return 0
  const base = last == null ? reps - 1 : last
  return ((base + 1) % len + len) % len
}

/**
 * Предложение контекста, в котором стоит пропуск. Пусто — пропуска нет вовсе.
 *
 * Нужно двум разным вещам, и потому вынесено: оборот вокруг пропуска (blankPhrase)
 * не имеет права выйти за границу предложения, а отметка незнакомого слова обязана
 * записать в журнал ЦЕЛОЕ предложение, а не показанный обрывок (см. `sentence` в
 * JournalLine — строка отметки самодостаточна).
 */
export function blankSentence(context: string): string {
  return splitSentences(context).find(s => /_{3,}/.test(s)) ?? ''
}

/* Сколько содержательных единиц (слово или формула) оставить вокруг пропуска.
   Числа выбраны замером по живой колоде 22.08.2026 (1200 контекстов, медиана
   предложения с пропуском — 12 слов), а не на глаз:

     1+3 → оборот 4 слова, 33% предложения (максимум 57%)
     2+3 → 5 слов, 40%
     1+4 → 5 слов, 40%
     2+4 → 6 слов, 48% (максимум 86% — это уже почти предложение)

   Три справа: различающий признак глагольного пропуска — вершина дополнения, и она
   на этой колоде укладывается в три токена («______ the claim», «______ an army
   that», «______ the ice-core record»); у прилагательного и существительного
   определяемое слово стоит ещё ближе («so ______ that the reactor», «strong
   ______ for calcium»). Четвёртый токен уже начинает тащить придаточное.

   Один слева: перед пропуском стоит служебное слово («to», «not», «cannot»,
   «helped»), оно задаёт часть речи и залог. Второе слово слева — это, как правило,
   подлежащее, то есть ровно та часть, по которой заученное предложение и узнаётся;
   ради 7 процентных пунктов различимости отдавать её не за что. */
export const PHRASE_BEFORE = 1
export const PHRASE_AFTER = 3

/** Многоточие на срезе: ученик обязан видеть, что ему показали обрывок, а не предложение. */
const ELLIPSIS = '…'

/**
 * Оборот вокруг пропуска: «The lawyer cited three precedents to ______ her central
 * argument.» → «… to ______ her central argument …».
 *
 * Зачем он есть. В режиме `cue: 'meaning'` на экране стоит только русское значение,
 * и для целого куста синонимов оно одно на всех: «подкреплять, укреплять» одинаково
 * описывает bolster, buttress, reinforce, corroborate и substantiate. Задание
 * получается неразрешимым — не потому, что ученик не знает слов, а потому, что
 * вопрос не содержит признака, по которому выбрать. Оборот этот признак возвращает:
 * «______ the alibi» и «______ morale» разводят кластер, оставаясь при этом далеко
 * не предложением.
 *
 * Почему не целое предложение. Опасение, из-за которого предложение отсюда убрали,
 * названо в C8 прямо: у слова три контекста, за десять повторов каждый вернётся
 * трижды, и ученик заучивает связку «предложение → слово» вместо значения. Оборот
 * этого не даёт: подлежащее и придаточные — та часть, по которой предложение
 * узнаётся, — остаются за срезом.
 *
 * Границы. Оборот не выходит за предложение с пропуском, формулу `$…$` берёт целиком
 * (segmentText отдаёт её одним куском, разрезать нечего) и обрывается перед самим
 * искомым словом, если оно стоит в предложении ещё раз в любой форме.
 */
export function blankPhrase(context: string, word: string, before = PHRASE_BEFORE, after = PHRASE_AFTER): string {
  const sentence = blankSentence(context)
  if (!sentence) return ''
  const segments = segmentText(sentence, { blanks: true })
  const blankAt = segments.findIndex(s => s.kind === 'blank')
  // пропуск внутри формулы: segmentText отдаёт формулу одним куском, и куска `blank` нет
  if (blankAt < 0) return ''

  const содержательный = (s: Segment) => s.kind === 'word' || s.kind === 'tex'
  const выдаётОтвет = (s: Segment) => s.kind === 'word' && isFormOf(s.text, word)

  let lo = blankAt
  for (let i = blankAt - 1, взято = 0; i >= 0 && взято < before; i--) {
    if (выдаётОтвет(segments[i])) break
    if (содержательный(segments[i])) взято++
    lo = i
  }
  let hi = blankAt
  for (let i = blankAt + 1, взято = 0; i < segments.length && взято < after; i++) {
    if (выдаётОтвет(segments[i])) break
    if (содержательный(segments[i])) взято++
    hi = i
  }

  const blanks = sentence.match(/_{3,}/g) ?? []
  let прочитаноПропусков = 0
  let out = ''
  for (let i = 0; i < segments.length; i++) {
    const s = segments[i]
    const text = s.kind === 'blank' ? (blanks[прочитаноПропусков++] ?? '______') : s.text
    if (i >= lo && i <= hi) out += text
  }
  const обрезаноСлева = segments.slice(0, lo).some(содержательный)
  const обрезаноСправа = segments.slice(hi + 1).some(содержательный)
  return (обрезаноСлева ? ELLIPSIS + ' ' : '') + out.trim() + (обрезаноСправа ? ' ' + ELLIPSIS : '')
}

/**
 * Это слово — форма загаданного? «buttress» / «buttresses» / «buttressed».
 *
 * Нужно ровно для одного: оборот вокруг пропуска не имеет права показать ответ.
 * Правило намеренно грубое в безопасную сторону — лишний срез стоит одного слова
 * контекста, показанный ответ стоит всего упражнения.
 */
function isFormOf(text: string, word: string): boolean {
  const t = text.toLowerCase()
  for (const часть of word.toLowerCase().split(/\s+/)) {
    if (!часть) continue
    if (t === часть || (часть.length >= 4 && (t.startsWith(часть) || часть.startsWith(t)))) return true
  }
  return false
}

const COMMON_PREPS = ['about', 'against', 'at', 'by', 'for', 'from', 'in', 'of', 'on', 'to', 'toward', 'with']

/** Варианты для prep-упражнения: правильный + 3 частотных предлога */
export function prepOptions(answer: string, n = 3): string[] {
  const distractors = shuffle(COMMON_PREPS.filter(p => p !== answer)).slice(0, n)
  return shuffle([answer, ...distractors])
}

/** Расстояние Левенштейна между строками (число правок). */
export function levenshtein(a: string, b: string): number {
  const m = a.length, n = b.length
  if (!m) return n
  if (!n) return m
  let prev = Array.from({ length: n + 1 }, (_, j) => j)
  for (let i = 1; i <= m; i++) {
    const cur = [i]
    for (let j = 1; j <= n; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1))
    }
    prev = cur
  }
  return prev[n]
}

/**
 * Исход объективного ответа. `twin` — введён СИНОНИМ загаданного слова (C10):
 * значение вспомнено, форма — нет. Это не промах и не успех, и именно поэтому
 * оно отдельное значение, а не флаг поверх `wrong`.
 */
export type TypeVerdict = 'correct' | 'typo' | 'twin' | 'wrong'

export function checkTyped(typed: string, word: string): TypeVerdict {
  const t = typed.trim().toLowerCase()
  const w = word.trim().toLowerCase()
  if (t === w) return 'correct'
  // опечатка: <= TYPO_MAX_EDITS правок при длине слова >= TYPO_MIN_LEN (пороги в journal.ts)
  if (w.length >= TYPO_MIN_LEN && levenshtein(t, w) <= TYPO_MAX_EDITS) return 'typo'
  return 'wrong'
}

/**
 * C10 (21.08.2026). Во «впиши слово» вариантов нет, и синоним из колоды —
 * законный ответ на то же предложение. Живой случай: «The lawyer cited three
 * precedents to ______ her central argument», введено `bolster` при загаданном
 * `buttress`. Оба в колоде, оба значат «подкреплять», оба сочетаются с
 * `argument`. Прежде это давало «Мимо» и Rating.Again: карточка уходила в
 * переучивание, difficulty росла — за верно вспомненное значение.
 *
 * Считать такой ответ верным тоже нельзя: тогда слово никогда не выучится, его
 * будет подменять привычный синоним. Поэтому Hard — ровно та оценка, для
 * которой FSRS и держит середину: вспомнил, но не то, что спрашивали.
 *
 * Двойник ищется ТОЛЬКО среди колоды: общее значение мы умеем доказать по
 * `meaning_ru` (см. meaningTwin), а про слово со стороны — нет. Молчаливо
 * прощать незнакомое слово значило бы прощать и опечатку, и чужой язык.
 *
 * Замер 22.08.2026 на кластере поддержки (12 глаголов: affirm, bolster, buttress,
 * cite, consolidate, corroborate, endorse, invoke, reinforce, substantiate,
 * sustain, validate — 132 упорядоченные пары): посимвольное сравнение кусков
 * прощало 12 пар, сравнение по основам — 38.
 *
 * Поле `confusables` вторым источником прощения НЕ используется, и это решение по
 * данным, а не по недосмотру. Тьютор перечисляет там всё, что путают, и самые
 * ценные его записи — как раз АНТОНИМЫ и близнецы по написанию. Замер той же даты
 * по живой колоде: среди пар «карточка ↔ её confusable той же части речи, лежащий
 * в колоде», которые правило по основам не прощает, ветка «confusable + общее
 * слово английского глосса» открыла бы 50 пар, и среди них implicit/explicit,
 * tangible/intangible, pertinent/irrelevant, spurious/legitimate, impartial/
 * partisan, profusion/paucity, haphazard/systematic, causation/correlation. В
 * режиме `cue: 'meaning'` значение стоит на экране, и введённый антоним означает
 * ровно ту путаницу, ради которой карточка и заведена: простить её — значит
 * никогда её не вылечить. Обратный ход (считать confusable запретом на прощение)
 * не работает по той же причине: у buttress в этом поле лежат bolster, reinforce
 * и substantiate — настоящие синонимы. Признака нужного знака в поле нет.
 */
export function typedTwin(typed: string, card: CardView, deck: CardView[]): CardView | null {
  const t = typed.trim().toLowerCase()
  if (!t || t === card.word.trim().toLowerCase()) return null
  const другое = deck.find(c => c.word.trim().toLowerCase() === t && c.path !== card.path)
  return другое && sharesMeaning(card, другое) ? другое : null
}

/** Парсинг числового ответа: "15", "-2.5", ".75", "3/4", запятая как точка */
export function parseNum(s: string): number | null {
  const t = s.trim().replace(',', '.')
  const frac = t.match(/^(-?\d+(?:\.\d+)?)\s*\/\s*(-?\d+(?:\.\d+)?)$/)
  if (frac) {
    const d = Number(frac[2])
    return d ? Number(frac[1]) / d : null
  }
  const n = Number(t)
  return Number.isFinite(n) && t !== '' ? n : null
}

/** Числовая проверка с относительным допуском (эквивалентные формы: 0.8 = 4/5) */
export function checkNumeric(typed: string, answer: string): TypeVerdict {
  const a = parseNum(answer)
  const t = parseNum(typed)
  if (a === null || t === null) {
    return typed.trim().toLowerCase() === answer.trim().toLowerCase() ? 'correct' : 'wrong'
  }
  return Math.abs(a - t) <= 1e-6 * Math.max(1, Math.abs(a)) ? 'correct' : 'wrong'
}

/**
 * Предлагаемая оценка по объективному результату (пользователь может переопределить).
 * Латентность учитывается: SAT — тест на скорость, верный-но-медленный ответ = Hard.
 * Опечатка предлагает Good: орфография на рецептивном экзамене не проверяется.
 */
/** Во сколько раз медленнее личной медианы ответ считается «трудным». */
export const SLOW_FACTOR = 2.5
/** Пол порога: ниже него «медленно» начнёт срабатывать на здоровых ответах. */
const SLOW_FLOOR_MS = 12_000

/**
 * Сколько ответов нужно виду карточек, чтобы верить его собственной медиане.
 * Меньше — шум: одна долгая ночная попытка сдвинет порог для всего вида.
 */
export const MIN_KIND_SAMPLES = 12

/**
 * Пол порога по видам, где в ответ входит чтение условия, а не только узнавание.
 * Замер 21.08.2026 по журналу: словарные ответы — медиана 8,1 с, карточки
 * разбора (kind error) — 21,6 с при p90 43,6 с. Общий пол в 12 с для них
 * означает, что нормальное чтение таблицы засчитывается как заминка.
 */
const KIND_FLOOR_MS: Record<string, number> = { math: 90_000, error: 45_000 }

/**
 * Порог «медленно» — доля от ЛИЧНОЙ медианы, а не константа.
 *
 * Стоял 25 000 мс при измеренной медиане ответа 7 412 мс и p90 17 827 мс, то
 * есть не достигался почти никогда. Результат виден в распределении оценок за
 * всю историю: Again 121, Hard 6, Good 271, Easy 3 — 98% в двух крайних
 * категориях. «Трудно» существовало на кнопке и не существовало в данных, а
 * FSRS различает Hard и Good именно затем, чтобы не гонять полузнание по тем же
 * интервалам, что и уверенное знание.
 *
 * ПОЧЕМУ МЕДИАНА ПО ВИДУ, А НЕ ОБЩАЯ. Общая медиана — это медиана словарных
 * ответов: их в журнале 447 из 464. Карточка разбора (kind error) требует
 * прочитать условие с таблицей и четыре длинных варианта, и её нормальный
 * ответ — 21,6 с при общем пороге 20,9 с. Итог замера 21.08.2026: 53% ответов
 * на такие карточки уходили в Hard против 12% у словарных, а Hard в состоянии
 * Learning не двигает ступень — карточка не выпускается и возвращается в каждый
 * следующий урок. Александр увидел один и тот же вопрос пятый раз именно так.
 *
 * Медиана берётся из журнала снаружи (`medianForKind`); без неё поведение
 * остаётся прежним.
 */
export function slowThresholdMs(kind = 'vocab', medianMs?: number): number {
  const floor = KIND_FLOOR_MS[kind] ?? SLOW_FLOOR_MS
  if (!medianMs || !Number.isFinite(medianMs) || medianMs <= 0) return Math.max(floor, 25_000)
  return Math.max(floor, Math.round(medianMs * SLOW_FACTOR))
}

/**
 * Медиана времени ответа для вида карточки: своя, пока её хватает на статистику,
 * иначе общая. Возвращать общую молча — единственный честный запасной путь:
 * пола по виду (KIND_FLOOR_MS) достаточно, чтобы холодный старт не наказывал
 * длинное условие.
 */
export function medianForKind(speed: { medianMs: number; byKind: Record<string, { medianMs: number; n: number }> }, kind = 'vocab'): number {
  const свой = speed.byKind[kind]
  return свой && свой.n >= MIN_KIND_SAMPLES && свой.medianMs > 0 ? свой.medianMs : speed.medianMs
}

/**
 * Замер это или его отсутствие.
 *
 * У порога «медленно» не было верхней границы: всё, что дольше
 * `slowThresholdMs`, приходило в FSRS как Hard — «трудно, но вспомнил».
 * Ответ через две минуты (отвлёкся, отложил телефон, вернулся) — не трудный
 * ответ, а отсутствие ответа, и Hard про него не сообщает ничего, кроме лишней
 * difficulty.
 *
 * Потолок здесь не новый — это `cardTimeCap` из journal.ts (60 c обычная
 * карточка, 180 c математика). Он уже означает ровно это: дальше замер
 * недействителен. Тем же потолком журнал режет зачётные минуты
 * (`minutesByDay`) и само поле `elapsed_ms` на записи (`journalElapsedMs`,
 * store.ts) — с формулировкой «это не медленный ответ, а отсутствие замера».
 * Путь оценки был единственным местом, куда потолок не доехал: `suggestedGrade`
 * получает сырой `answeredMs` прямо с экрана (Review.tsx), а не из журнала.
 * Второй истины о том же не заводим — берём ту, что уже есть.
 *
 * Числа живого журнала на 21.08.2026 (523 оценки, format ≠ intro): медиана
 * словарного ответа 8 204 мс, p90 27,6 c, p95 65,5 c, максимум 25 минут.
 * Порог «медленно» для словаря = 20,5 c, потолок замера = 60 c, то есть 7,3
 * медианы; между ними и живёт честное «медленно». Выше потолка 28 строк из 523
 * (5,4%) — и это ровно те 28 строк, ради которых в store.ts появился
 * `journalElapsedMs`.
 *
 * ПОЧЕМУ ВЫШЕ ПОТОЛКА — Good, А НЕ Again. Соблазн назвать такой ответ провалом
 * данные не подтверждают: среди 25 ответов дольше минуты с объективным исходом
 * верных 18 (72%). Провалом их объявить значит выписать карточке lapse и
 * поднять difficulty за верно вспомненное слово — та самая порча модели,
 * от которой колода уже пострадала (медиана difficulty 9,08 из 10 при нуле
 * зрелых карточек). Поэтому латентность просто перестаёт участвовать в решении,
 * а исход остаётся: верно — Good, неверно — Again (ветка выше).
 *
 * Побочное следствие, названное вслух: у карточек разбора (kind error) медиана
 * ответа 24,3 c, порог «медленно» = 60,8 c, а потолок замера — 60 c. Окно Hard
 * по латентности у них схлопывается почти в ноль, и оценку определяет
 * объективный исход. Для карточки, где ответ — это чтение таблицы и четырёх
 * длинных вариантов, это верно: минута там измеряет чтение, а не память.
 */
function isMeasured(elapsedMs: number, kind: string): boolean {
  return Number.isFinite(elapsedMs) && elapsedMs <= cardTimeCap(kind)
}

/**
 * Оценка, предложенная по объективному исходу. Вердикт приходит целиком, а не
 * парой булевых: `correct`/`typo` допускали комбинацию, которой не бывает, и
 * четвёртый исход (`twin`, C10) в эту пару уже не помещался.
 */
export function suggestedGrade(format: Format, verdict: TypeVerdict, elapsedMs = 0, kind = 'vocab', medianMs?: number): Grade | null {
  if (format === 'reveal' || format === 'intro') return null
  if (verdict === 'wrong') return Rating.Again
  // синоним: значение вспомнено, форма — нет; скорость тут уже ничего не решает
  if (verdict === 'twin') return Rating.Hard
  if (isMeasured(elapsedMs, kind) && elapsedMs > slowThresholdMs(kind, medianMs)) return Rating.Hard
  return Rating.Good
}

/** Прогноз нагрузки: сколько учебных единиц придёт на повтор в ближайшие N дней (просрочка → сегодня) */
export function loadForecast(cards: CardView[], days = 7, now: Date = new Date()): number[] {
  const out = new Array(days).fill(0)
  const today = dayKey(now)
  const dayKeys = Array.from({ length: days }, (_, k) => addDaysKey(today, k))
  for (const i of expandItems(cards, now)) {
    if (i.fsrs.state === State.New) continue
    let d = dayKey(i.fsrs.due)
    if (d < today) d = today
    const idx = dayKeys.indexOf(d)
    if (idx >= 0) out[idx]++
  }
  return out
}

/**
 * Счётчики для главного экрана (в учебных единицах: карточка × навык).
 * newAvail тоже гасится NEW_STOP_DATE — иначе плашка «N новых» на Home обещала бы
 * ввод, которого buildQueue уже не даст, и расходилась бы с настоящим уроком.
 *
 * А вот потолки урока и дня (MAX_REVIEW_PER_LESSON / MAX_REVIEW_PER_DAY) здесь
 * сознательно НЕ применяются: `revDue` — это долг, а не порция. Потолок
 * растягивает выдачу во времени и не отменяет ни одной карточки, поэтому
 * просрочка, не влезшая в сегодняшний лимит, обязана остаться в счётчике
 * «повторить» — иначе она молча исчезнет с экрана, а вместе с ней и повод
 * заниматься завтра. Ровно по этой причине потолок дня считается по разделу и
 * живёт в buildQueue: этот же счётчик вызывается и на всю колоду сразу
 * (Home.tsx, Stats.tsx), где потолок раздела ничего не значит.
 */
export function homeCounts(cards: CardView[], newBudget: number, now: Date = new Date()) {
  const eod = endOfStudyDay(now)
  const items = expandItems(cards, now)
  const learnDue = items.filter(i => isLearning(i.fsrs.state) && i.fsrs.due.getTime() <= now.getTime() + LEARN_AHEAD_MS).length
  const revDue = items.filter(i => i.fsrs.state === State.Review && i.fsrs.due.getTime() < eod.getTime()).length
  const newAvail = Math.min(items.filter(i => i.fsrs.state === State.New).length, Math.max(0, newIntroAllowed(now) ? newBudget : 0))
  /* «Завтра» — это срок внутри ЗАВТРАШНЕГО учебного дня: окно [конец сегодняшнего
     дня; +24 часа). Обе половины счёта — и повторы, и learning — считаются по
     одному окну, потому что нижняя граница у них общая и она одна: конец
     учебного дня (daytime.ts::endOfStudyDay, rollover 04:00).

     Так было не всегда. У повторов нижняя граница стояла (`t >= eod`), а у
     learning — `due > now + LEARN_AHEAD_MS`, то есть момент внутри СЕГОДНЯШНЕГО
     дня. Карточка, которую ещё предстоит доучить сегодня вечером, попадала в
     плашку «завтра»: в 20:00 слово со сроком 23:00 обещалось на завтра, хотя
     приходило через три часа. Число на главном экране складывалось из
     сегодняшнего долга и завтрашнего плана, и планировать по нему было нельзя. */
  const завтра = eod.getTime() + 86400_000
  const revTomorrow = items.filter(i => {
    const t = i.fsrs.due.getTime()
    return i.fsrs.state !== State.New && t >= eod.getTime() && t < завтра
  }).length
  const active = cards.filter(c => !c.suspended)
  const byState = {
    new: active.filter(c => c.fsrs.state === State.New).length,
    learning: active.filter(c => isLearning(c.fsrs.state)).length,
    review: active.filter(c => c.fsrs.state === State.Review).length
  }
  return { learnDue, revDue, newAvail, revTomorrow, byState, total: active.length }
}
