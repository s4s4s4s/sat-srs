/**
 * Русское число с существительным: «1 ответ · 2 ответа · 12 ответов».
 *
 * Подписи в приложении читаются вслух, а не как счётчик, поэтому «2 ответов» — брак,
 * а не мелочь. Правило одно на всё приложение намеренно: до этого оно было списано
 * от руки дважды (подпись упражнений на главной и подпись слов в чтении), и третья
 * копия под практику превратила бы совпадение в привычку.
 *
 * Формы — как в словаре: `одно` для 1, `два` для 2–4, `много` для 0, 5–20 и далее по кругу.
 * Одиннадцать–четырнадцать — исключение, они берут форму «много» несмотря на последнюю цифру.
 */
export function множ(n: number, одно: string, два: string, много: string): string {
  const ten = Math.abs(n) % 100
  const one = Math.abs(n) % 10
  const слово = ten >= 11 && ten <= 14 ? много
    : one === 1 ? одно
      : one >= 2 && one <= 4 ? два
        : много
  return `${n} ${слово}`
}
