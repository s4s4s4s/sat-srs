import { State } from 'ts-fsrs'
import { itemKey } from './scheduler'
import type { StudyItem } from './types'

/**
 * Полоска прогресса урока: обе части дроби — в ПОКАЗАХ (экранах).
 *
 * Раньше числителем шли сделанные ПОКАЗЫ, а знаменателем — показы плюс длина очереди
 * в ЭЛЕМЕНТАХ. Единицы разные: один элемент очереди даёт от одного до трёх показов,
 * и очередь по ходу урока ещё растёт. Отсюда всё сразу: систематическое завышение
 * (на восьмом экране из шестнадцати полоска показывала 87,5%), откаты назад на 30 и
 * 53 пункта в момент добора и невозможность дойти до 100% (текущая карточка всегда
 * сидела в знаменателе и никогда в числителе).
 *
 * Здесь знаменатель — оценка ВСЕХ показов урока: очередь плюс обязательная работа,
 * которая в очередь ещё не встала (слова, введённые сегодня и недоработанные), плюс
 * минимальный резерв под лестницу добора. Оценка приблизительна по своей природе —
 * заполнители и лишнее новое слово подтягиваются только когда урок иначе встанет, —
 * поэтому поверх неё в Review.tsx стоит храповик: показанный процент не уменьшается.
 * Ученик может видеть, что идёт медленнее, чем думал; он не должен видеть, что идёт назад.
 */

/**
 * Сколько раз урок обязан отработать слово, введённое сегодня, прежде чем счесть его
 * закрытым (лестница добора `topUp` в Review.tsx). Здесь же, а не в экране, потому что
 * от этого числа зависит и знаменатель полоски, и момент завершения урока.
 */
export const DRILL_PER_SESSION = 2

/** Обычный экран (повтор, упражнение, разбор) — один показ. */
export const SHOWS_PER_REPEAT = 1

/**
 * Окно-знакомство — ДВА показа: само окно (оценки не даёт, A7) и отработка, которую
 * урок обязан дать следом, иначе знакомство не выдаётся вовсе (A6, `hasSeparator`).
 */
export const SHOWS_PER_INTRO = 2

export interface ProgressInput {
  /** Показов, уже завершённых учеником. Текущий экран сюда НЕ входит. */
  shown: number
  /** Очередь урока; `queue[0]` — карточка, которая на экране прямо сейчас. */
  queue: readonly StudyItem[]
  /** Обязательная работа урока, ещё не стоящая в очереди (`topUp()` минус очередь). */
  pending: readonly StudyItem[]
  /** Отрисуется ли единица окном-знакомством (`screenFormat(...) === 'intro'`). */
  isIntro: (item: StudyItem) => boolean
  /** Сколько окон-знакомств урок ещё может выдать (`OrderCtx.introsLeft`). */
  introsLeft: number
  /** `itemKey` слов, которым знакомство уже показано в этой сессии. */
  introduced: ReadonlySet<string>
  /** Слова, которые урок обязан отработать сегодня (`forcedTodaySlugs`). */
  forced: ReadonlySet<string>
  /** `itemKey` → сколько раз слово уже оценено в ЭТОЙ сессии. */
  drilled: ReadonlyMap<string, number>
  /** Лестница добора может поднять заполнитель — ранний повтор (`OrderCtx.hasFiller`). */
  fillerAvailable: boolean
  /** Все лишние новые слова, которые лестница ещё вправе ввести сверх плана (`bonusNew`). */
  bonusNew: readonly StudyItem[]
}

/**
 * Отработок, которые уроку ещё предстоит провести по этой единице (без окна-знакомства).
 *
 * Горизонт единицы, СТОЯЩЕЙ В ОЧЕРЕДИ, — один показ. Вернётся ли карточка в этот же урок
 * ещё раз, в момент показа не известно: learning-шаг возвращает её только если очередь
 * длиннее нужной паузы (`requeuePosition` иначе отдаёт null), а сегодняшнее слово уходит
 * из добора совсем, как только выпускается из Learning в Review. Второй показ попадает в
 * знаменатель тогда, когда урок его действительно затребует, — очередью или добором.
 *
 * Единица из `pending` — другое дело: она в оценке ровно потому, что `topUp` её требует,
 * и требовать будет, пока не наберётся DRILL_PER_SESSION отработок. Это уже не прогноз,
 * а обязательство урока, и оно считается целиком.
 *
 * Замер на 721 смоделированном уроке: горизонт «одна отработка на очередную единицу»
 * доводит до ровных 100% 390 уроков против 250 у варианта «считать все обязательные
 * отработки заранее», а суммарный недобор падает со 154 до 88 пунктов.
 */
function drillsLeftFor(item: StudyItem, input: ProgressInput, pending: boolean): number {
  return pending && input.forced.has(item.view.slug)
    ? Math.max(SHOWS_PER_REPEAT, DRILL_PER_SESSION - (input.drilled.get(itemKey(item)) ?? 0))
    : SHOWS_PER_REPEAT
}

/** Новое слово, которому знакомство в этой сессии ещё не показывали (session.ts::isFreshNew). */
function isFreshNew(item: StudyItem, input: ProgressInput): boolean {
  return item.fsrs.state === State.New && !input.introduced.has(itemKey(item))
}

/**
 * Оценка числа показов, которые уроку осталось выдать (текущий экран включён).
 *
 * Две причины, по которым единица из очереди не даст ни одного показа, — обе взяты
 * из правил урока, а не выдуманы здесь:
 *
 * 1. Урочный лимит окон-знакомств (`introsLeft`). Он тратится по ходу очереди; новое
 *    слово, на которое окна не хватило, урок не покажет вовсе и оставит следующему
 *    (`overIntroLimit` в session.ts). Без этого вычета урок из четырёх экранов, где в
 *    очереди застряли два непоказуемых новых слова, заканчивался на 44%.
 *
 * 2. A6: знакомство выдаётся, только если между окном и первой отработкой урок сможет
 *    вставить показ ДРУГОГО слова (`hasSeparator` в session.ts). Когда вся оставшаяся
 *    работа урока — это текущий экран, разделителю взяться неоткуда, и новое слово
 *    уходит в следующий урок непоказанным. Без этого вычета урок из двенадцати экранов
 *    заканчивался на 85,7%: полоска до конца ждала знакомство, которого не будет.
 *
 * Второй вычет намеренно сделан «структурным», без учёта времени: `hasSeparator` умеет
 * отказать и по разрыву A2 (сосед показан секунду назад), но такой отказ проходит сам
 * собой, а занижение оценки под храповиком не отыграть — полоска встанет на 100% раньше
 * конца урока. Поэтому здесь считается только то, чего в уроке не случится никогда:
 * разделителей нет ни одного и добрать их лестнице нечем — ни заполнителем, ни лишним
 * новым словом (оно и само может стать разделителем: два новых слова годятся друг
 * другу, если лимит окон выдерживает оба, — это правило самого `hasSeparator`).
 */
export function estimateShowsLeft(input: ProgressInput): number {
  const units = [...input.queue, ...input.pending]
  const wantsIntro = units.map(it => input.isIntro(it))
  const freshNew = units.map(it => isFreshNew(it, input))

  // 1) бюджет окон-знакомств тратится по порядку очереди — как его тратит сам урок
  let introsLeft = input.introsLeft
  const shows = units.map((it, i) => {
    if (wantsIntro[i] && introsLeft > 0) {
      introsLeft--
      return drillsLeftFor(it, input, i >= input.queue.length) + (SHOWS_PER_INTRO - SHOWS_PER_REPEAT)
    }
    // окно не влезло в лимит: новое слово ждёт следующего урока и показов не даст,
    // а «Подзабылось» отработается обычным упражнением — без окна, но экраном
    if (wantsIntro[i] && freshNew[i]) return 0
    return drillsLeftFor(it, input, i >= input.queue.length)
  })

  /* 2) A6: разделитель — любой показ другого слова ПОСЛЕ окна-знакомства. Текущий экран
     (`units[0]`) идёт раньше окна и разделителем быть не может, поэтому вычитается.
     Само `units[0]` не проверяется: оно уже на экране, а брошенное знакомство на первой
     позиции снимает сам урок (ветка пропуска в Review.tsx). Зануление одного слова
     отнимает разделитель у соседа, поэтому проход повторяется до неподвижности. */
  if (!input.fillerAvailable && !input.bonusNew.length) {
    for (let pass = 0; pass < units.length; pass++) {
      let changed = false
      for (let i = 1; i < units.length; i++) {
        if (!wantsIntro[i] || !freshNew[i] || !shows[i]) continue
        let separators = 0
        for (let j = 0; j < units.length; j++) {
          if (j === i || units[j].view.path === units[i].view.path) continue
          separators += shows[j]
        }
        if (units[0].view.path !== units[i].view.path) separators-- // текущий экран уже идёт
        if (separators < SHOWS_PER_REPEAT) { shows[i] = 0; changed = true }
      }
      if (!changed) break
    }
  }

  return shows.reduce((a, b) => a + b, 0)
}

/**
 * Доля пройденного урока, 0..1. Текущий экран считается сделанным: иначе последний экран
 * урока навсегда упирался бы в «осталась одна карточка» и полоска заканчивалась бы на 75%
 * в уроке из четырёх экранов.
 *
 * К оценке очереди добавляются экраны, которые лестница добора ещё вправе себе выписать.
 * Без них полоска показывала 100% на пятом экране из семи — такая же ложь, как 75% на
 * последнем: урок грамматики из пяти карточек штатно дотягивает себя двумя новыми.
 */
export function lessonProgress(input: ProgressInput): number {
  const showsLeft = estimateShowsLeft(input)
  const numerator = input.shown + 1
  let total = input.shown + showsLeft

  /* Лишние новые слова, которые лестница ещё вправе ввести. Их число известно точно
     (урочный запас и дневной остаток), а вот сколько экранов даст каждое — зависит от
     раздела: грамматике и математике окно-знакомство не положено, такой экран урок выдаст
     сразу, а словарному слову нужно окно, окну — отработка, и между ними разделитель (A6).
     Если кроме текущего экрана показывать больше нечего, разделителя не будет: урок добавит
     слово в очередь и тут же закончится, бросив его, — под такое место не резервируется. */
  let room = showsLeft
  for (const bonus of input.bonusNew) {
    const needsIntro = input.isIntro(bonus)
    if (needsIntro && room <= SHOWS_PER_REPEAT) break
    const add = needsIntro ? SHOWS_PER_INTRO : SHOWS_PER_REPEAT
    total += add
    room += add
  }

  /* Заполнитель — обычное упражнение; сколько их поднимется, заранее не известно (лестница
     берёт пачку `MAX_EARLY_FILLERS`, когда иначе показывать нечего), но не меньше одного. */
  if (input.fillerAvailable) total = Math.max(total, numerator + SHOWS_PER_REPEAT)

  return numerator / Math.max(total, numerator)
}
