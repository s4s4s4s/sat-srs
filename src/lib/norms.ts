import { RUN_MIN_REVIEWS } from './journal'
import type { Section } from './scheduler'

/**
 * Нормы дня.
 *
 * У дня был один жёсткий лимит новых карточек, и он работал как стена: выбрал —
 * приложение пишет «Всё повторено» и заниматься больше нечем. До экзамена
 * считанные недели, и такая стена вредна. Норм теперь три, и все три видны
 * одновременно — засечками на полосе дня: пол держит серию, оптимум задаёт цель,
 * максимум остаётся единственной честной границей.
 */

/** Уровень нормы: пол дня · цель дня · потолок дня */
export type NormLevel = 'min' | 'norm' | 'max'

/** Порядок уровней от меньшего к большему — по нему ищутся взятое и следующее. */
export const NORM_LEVELS: readonly NormLevel[] = ['min', 'norm', 'max']

/** Родительный падеж для подписей вида «до оптимума 6». */
export const NORM_TITLE_GENITIVE: Record<NormLevel, string> = {
  min: 'минимума',
  norm: 'оптимума',
  max: 'максимума'
}

/**
 * Упражнений за день.
 *
 * Числа взяты из журнала владельца, а не назначены. 14 учебных дней дают медиану
 * 34 упражнения, p75 — 67, максимум 187 (27.07.2026).
 *
 * Про 187 существовал вывод «такой день вреден»: после него три дня тишины, а за
 * первые двадцать дней августа занятия были всего трижды. Вывод ОПРОВЕРГНУТ:
 * 29.07.2026 владелец переехал в Ереван, и провал объясняется переездом, а не
 * перегрузом. Данных о вреде большого дня нет, поэтому максимум здесь — третья
 * цель, а не запрет: полоса на нём заканчивается, занятия — нет.
 *
 * Минимум — тот же пол дня, что держит серию (`RUN_MIN_REVIEWS` в journal.ts), и
 * выражен через него, а не переписан числом: два независимых числа про одну
 * величину разъезжаются при первой же правке одного из них.
 * Оптимум 40 — чуть выше медианы: цель должна быть целью, а не констатацией уже
 * достигнутого. Максимум 120 — выше двух последних дней (84 и 108): цель, до
 * которой ещё надо дотянуться, иначе она превращается в стену тем же вечером,
 * когда её поставили.
 *
 * Настоящая граница дня не здесь, а в `NEW_PER_DAY`: ввод новых карточек
 * оплачивается завтрашними повторениями, и ограничивать надо именно его.
 * Повторения уже введённого не ограничены ничем.
 */
export const DAY_NORMS: Record<NormLevel, number> = {
  min: RUN_MIN_REVIEWS,
  norm: 40,
  max: 120
}

/**
 * Прежняя общая норма ввода - до WS6b была единственным лимитом на всю колоду.
 * Математика лимита по разделу не получает (в долг RW она не входит, см.
 * `RW_WEIGHTS` в dayplan.ts) и держится на этих же числах без изменений.
 */
const OLD_NEW_PER_DAY: Record<NormLevel, number> = {
  min: 2,
  norm: 8,
  max: 14
}

/**
 * Норма новых карточек за день - СВОЯ у каждого раздела (WS6b), не одна на всю колоду.
 *
 * Единый `NEW_PER_DAY` был единственной нормой ввода: 8 новых слов в день дают
 * около 48 оценок знакомства при медиане дня 34 упражнения, и раздел словаря
 * забирал день целиком, даже когда `kindRank` в scheduler.ts ставил грамматику
 * вперёд, - `freshItems` работает внутри своего раздела, и приоритет между
 * разделами никогда не срабатывал. Замер журнала: 94% оценок ушли в словарь,
 * разделы SEC (грамматика) и EOI - ноль оценок за три месяца.
 *
 * `grammar` и `logic` получили нормы выше `rw`, чтобы у пустого раздела было чем
 * заполнить свою долю дня, как только `nextSection` (dayplan.ts) поставит его
 * первым. `rw` (словарь) получил норму ниже прежней общей - именно её раздутый
 * бюджет забирал день целиком.
 */
export const NEW_PER_DAY_BY_SECTION: Record<Section, Record<NormLevel, number>> = {
  rw: { min: 1, norm: 3, max: 5 },
  grammar: { min: 2, norm: 8, max: 10 },
  logic: { min: 2, norm: 6, max: 8 },
  math: OLD_NEW_PER_DAY
}

/** Норма новых карточек дня для конкретного раздела и уровня - см. `NEW_PER_DAY_BY_SECTION`. */
export function newPerDay(section: Section, level: NormLevel): number {
  return NEW_PER_DAY_BY_SECTION[section][level]
}

/**
 * Обратная совместимость: старые вызовы, ещё не переведённые на `newPerDay`
 * (Review.tsx, Stats.tsx, main.tsx - лимит дня для урока и бейдж вне главного
 * экрана), читают ЭТУ константу. Указывает на таблицу `rw`, а не на прежние
 * {2, 8, 14}: раньше 94% оценок и так были словарными, и общий лимит дня по
 * смыслу и был лимитом на словарь.
 */
export const NEW_PER_DAY: Record<NormLevel, number> = NEW_PER_DAY_BY_SECTION.rw

/** Новых за один урок: столько же, сколько было настройкой по умолчанию. */
export const NEW_PER_LESSON = 5

export interface DayNormStatus {
  /** Наибольший уже взятый уровень; null — не взят даже пол. */
  reached: NormLevel | null
  /** Следующая цель; null — взят максимум. */
  next: { level: NormLevel; target: number } | null
}

/**
 * Что уже взято и что следующее - по числу упражнений дня.
 *
 * Аргумент называется `units`, а не `reviews`: с WS6a вызывающий передаёт сюда
 * `dayUnitsByDay` (оценки карточек + практика в единицах, journal.ts), а не
 * только оценки карточек. Сигнатура и пороги DAY_NORMS не меняются - число
 * упражнений считается снаружи.
 */
export function dayNormStatus(units: number): DayNormStatus {
  let reached: NormLevel | null = null
  for (const level of NORM_LEVELS) {
    if (units >= DAY_NORMS[level]) reached = level
  }
  const next = NORM_LEVELS.find(level => units < DAY_NORMS[level])
  return { reached, next: next ? { level: next, target: DAY_NORMS[next] } : null }
}

/** Доля заполнения шкалы дня, 0..1; 100% - максимум дня. `units` - см. dayNormStatus. */
export function dayNormFill(units: number): number {
  if (!(units > 0)) return 0
  return Math.min(1, units / DAY_NORMS.max)
}
