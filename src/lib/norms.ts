import { RUN_MIN_REVIEWS } from './journal'

/**
 * Нормы дня.
 *
 * У дня был один жёсткий лимит новых карточек, и он работал как стена: выбрал —
 * приложение пишет «Всё повторено» и заниматься больше нечем. До экзамена
 * считанные недели, и такая стена вредна. Норм теперь три, и все три видны
 * одновременно — засечками на полосе дня: пол держит серию, оптимум задаёт цель,
 * максимум остаётся единственной честной границей.
 */

/** Уровень нормы: пол дня · цель дня · потолок дня */
export type NormLevel = 'min' | 'norm' | 'max'

/** Порядок уровней от меньшего к большему — по нему ищутся взятое и следующее. */
export const NORM_LEVELS: readonly NormLevel[] = ['min', 'norm', 'max']

/** Родительный падеж для подписей вида «до оптимума 6». */
export const NORM_TITLE_GENITIVE: Record<NormLevel, string> = {
  min: 'минимума',
  norm: 'оптимума',
  max: 'максимума'
}

/**
 * Упражнений за день.
 *
 * Числа взяты из журнала владельца, а не назначены. 14 учебных дней дают медиану
 * 34 упражнения, p75 — 67, максимум 187 (27.07.2026).
 *
 * Про 187 существовал вывод «такой день вреден»: после него три дня тишины, а за
 * первые двадцать дней августа занятия были всего трижды. Вывод ОПРОВЕРГНУТ:
 * 29.07.2026 владелец переехал в Ереван, и провал объясняется переездом, а не
 * перегрузом. Данных о вреде большого дня нет, поэтому максимум здесь — третья
 * цель, а не запрет: полоса на нём заканчивается, занятия — нет.
 *
 * Минимум — тот же пол дня, что держит серию (`RUN_MIN_REVIEWS` в journal.ts), и
 * выражен через него, а не переписан числом: два независимых числа про одну
 * величину разъезжаются при первой же правке одного из них.
 * Оптимум 40 — чуть выше медианы: цель должна быть целью, а не констатацией уже
 * достигнутого. Максимум 120 — выше двух последних дней (84 и 108): цель, до
 * которой ещё надо дотянуться, иначе она превращается в стену тем же вечером,
 * когда её поставили.
 *
 * Настоящая граница дня не здесь, а в `NEW_PER_DAY`: ввод новых карточек
 * оплачивается завтрашними повторениями, и ограничивать надо именно его.
 * Повторения уже введённого не ограничены ничем.
 */
export const DAY_NORMS: Record<NormLevel, number> = {
  min: RUN_MIN_REVIEWS,
  norm: 40,
  max: 120
}

/**
 * Новых карточек за день — НА РАЗДЕЛ (см. `newBudgetFor` в scheduler.ts: предметы
 * разведены по разделам, и норма ввода считается по предмету).
 * Оптимум 8 — рабочая норма, которой раньше был единственный жёсткий лимит;
 * максимум 14 — запас, который снимает стену, но не возвращает ввод пачками.
 */
export const NEW_PER_DAY: Record<NormLevel, number> = {
  min: 2,
  norm: 8,
  max: 14
}

/** Новых за один урок: столько же, сколько было настройкой по умолчанию. */
export const NEW_PER_LESSON = 5

export interface DayNormStatus {
  /** Наибольший уже взятый уровень; null — не взят даже пол. */
  reached: NormLevel | null
  /** Следующая цель; null — взят максимум. */
  next: { level: NormLevel; target: number } | null
}

/** Что уже взято и что следующее — по числу сделанных сегодня упражнений. */
export function dayNormStatus(reviews: number): DayNormStatus {
  let reached: NormLevel | null = null
  for (const level of NORM_LEVELS) {
    if (reviews >= DAY_NORMS[level]) reached = level
  }
  const next = NORM_LEVELS.find(level => reviews < DAY_NORMS[level])
  return { reached, next: next ? { level: next, target: DAY_NORMS[next] } : null }
}

/** Доля заполнения шкалы дня, 0..1; 100% — максимум дня. */
export function dayNormFill(reviews: number): number {
  if (!(reviews > 0)) return 0
  return Math.min(1, reviews / DAY_NORMS.max)
}
