/**
 * «Почему?» — разбор задания моделью прямо в уроке.
 *
 * Зачем. Карточка объясняет, ЧТО верно (`meaning_ru`, `explain`), но не объясняет,
 * почему выбранный вариант не подходит ИМЕННО ЗДЕСЬ. Между «corroborate» и
 * «bolster» разница не в переводе — она в том, что подтверждают доказательствами
 * гипотезу, а укрепляют уже существующую позицию. Такой разбор нельзя заготовить
 * в колоде: он зависит от того, что ученик выбрал, а вариантов пар — сотни.
 *
 * Куда уходит запрос. Не в API Anthropic — тот стоит отдельных денег поверх
 * подписки. Разбор пишет Claude Code на домашней машине: приложение кладёт наряд
 * в очередь всегда живого воркера (контур «Штурмана», маршрут `/why`), раннер на
 * машине забирает его, гоняет модель под подпиской и возвращает текст, а
 * приложение забирает готовое опросом. Отсюда два следствия, которые видит
 * ученик: разбор приезжает целиком примерно за полминуты, а не печатается на
 * глазах, и его не будет вовсе, пока машина выключена.
 *
 * Что уезжает в наряд. Только факты показа — задание, правильный ответ и выбор
 * ученика. Инструкция модели живёт на машине (`pc/prompts/why.md` в контуре), и
 * это не мелочь: токен из настроек телефона даёт право заказать разбор задания
 * SAT, но не произвольный текст от чужой подписки.
 *
 * Устройство файла — как в `sound.ts`: чистые функции (`whyBody`, `cacheKey`)
 * проверяет тест в Node, сеть живёт в одном тонком `askWhy`.
 */

/** Дверь очереди нарядов. Не секрет — секрет только токен, он в настройках. */
const WHY_URL = 'https://shturman.vault-78edd5.workers.dev/why'

/* Шаг опроса готовности. Полторы секунды — заметно меньше, чем шаг раннера на
   машине (четыре), поэтому лишним ожиданием разбор здесь не задерживается. */
const POLL_MS = 1500
/* Сколько всего ждать разбор. Замер на боевом контуре 20.08.2026: от заказа до
   готового текста 30 секунд — модель пишет около двадцати пяти, остальное уходит
   на то, чтобы раннер забрал наряд. Сто секунд — это запас на
   занятую очередь; дальше ученику честнее сказать, что не дождались, чем
   держать его у экрана. */
const WAIT_MS = 100_000
/* Ниже этого молчания машину считаем спящей. Раннер приходит за нарядами раз в
   четыре секунды, но, пока он гоняет модель по другому наряду, не приходит
   вовсе — а самый долгий из них идёт до пяти минут. Отсюда и порог: он не
   торопится обвинять живую машину, а служит только формулировкой отказа. */
const PC_ASLEEP_SEC = 330

export class CoachError extends Error {
  constructor(public status: number, message: string) { super(message) }
}

/** Всё, что нужно знать модели о конкретном показе. Собирает экран урока. */
export interface WhyAsk {
  kind: string        // vocab | grammar | math | error
  word: string        // слово карточки (у грамматики — название правила)
  pos: string
  meaningEn: string
  meaningRu: string
  roots: string
  sentence: string    // предложение с пропуском, как его видел ученик
  sentenceRu: string  // перевод предложения, если он есть в колоде
  answer: string      // что было правильным ответом
  picked: string      // что выбрал или ввёл ученик; пусто = ответа не было («не помню», показ)
  explain: string     // авторское пояснение из карточки, если есть
}

/** Что происходит прямо сейчас — этим панель объясняет ожидание. */
export type WhyStage = 'заказано' | 'машина пишет'

/**
 * Тело наряда: ровно поля `WhyAsk`, без единого лишнего.
 *
 * Отдельной функцией, а не встроенным литералом, потому что это контракт с
 * очередью: она проверяет состав и длины полей и отвергает всё, чего не знает.
 */
export function whyBody(a: WhyAsk): Record<string, string> {
  return {
    kind: a.kind,
    word: a.word,
    pos: a.pos,
    meaningEn: a.meaningEn,
    meaningRu: a.meaningRu,
    roots: a.roots,
    sentence: a.sentence,
    sentenceRu: a.sentenceRu,
    answer: a.answer,
    picked: a.picked,
    explain: a.explain
  }
}

/* FNV-1a: ключу кэша нужна не криптография, а стабильность и короткая строка.
   Тот же алгоритм считает идентификатор наряда на той стороне — совпадение не
   обязательно, но и расхождение ничего не ломает: ключи живут порознь. */
function hash(s: string): string {
  let h = 0x811c9dc5
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return (h >>> 0).toString(36)
}

/**
 * Ключ кэша разбора. В него входит всё, от чего разбор зависит: предложение,
 * правильный ответ и выбор ученика. Правка предложения в колоде меняет ключ —
 * старый разбор не всплывёт под новым текстом.
 */
export function cacheKey(a: WhyAsk): string {
  return `why:${hash([a.kind, a.word, a.sentence, a.answer, a.picked].join(' '))}`
}

/** Человеческая причина отказа — её показывают в панели вместо кода ошибки. */
function поЧемуОтказ(status: number, тело: string): string {
  if (status === 401 || status === 403) return 'токен разбора не принят — проверьте его в настройках'
  if (status === 400) return тело ? `очередь не приняла задание: ${тело}` : 'очередь не приняла задание'
  if (status === 404) return 'разбор потерялся в очереди — попробуйте ещё раз'
  if (status >= 500) return 'очередь разборов сейчас недоступна'
  return тело ? `ошибка ${status}: ${тело}` : `ошибка ${status}`
}

/** Отказ по молчанию машины — формулировка зависит от того, приходила ли она. */
function поЧемуМолчит(pcAgo: number | null): string {
  if (pcAgo === null) return 'домашний компьютер ещё ни разу не выходил на связь — разбор писать некому'
  if (pcAgo > PC_ASLEEP_SEC) return 'домашний компьютер выключен — разбор появится, когда он включён'
  return 'компьютер занят и не успел ответить — попробуйте ещё раз через минуту'
}

interface Ответ {
  ok?: boolean
  id?: string
  state?: 'pending' | 'taken' | 'done' | 'expired'
  text?: string
  error?: string
  pcAgo?: number | null
}

/** Один запрос к очереди: разбирает и отказ, и тело, одинаково для обоих концов. */
async function запрос(url: string, token: string, тело?: unknown): Promise<Ответ> {
  let res: Response
  try {
    res = await fetch(url, {
      method: тело ? 'POST' : 'GET',
      headers: {
        authorization: `Bearer ${token}`,
        ...(тело ? { 'Content-Type': 'application/json' } : {})
      },
      ...(тело ? { body: JSON.stringify(тело) } : {})
    })
  } catch {
    throw new CoachError(0, 'нет связи с очередью разборов')
  }

  const данные: Ответ = await res.json().catch(() => ({}))
  if (!res.ok) throw new CoachError(res.status, поЧемуОтказ(res.status, (данные.error ?? '').slice(0, 200)))
  return данные
}

const пауза = (ms: number) => new Promise(r => setTimeout(r, ms))

export interface AskOptions {
  /** Сообщает, что происходит: заказано / машина взялась писать. */
  onStage?: (s: WhyStage) => void
  /** Шаг опроса и общий потолок ожидания; боевые значения — по умолчанию. */
  pollMs?: number
  waitMs?: number
  /** Часы. Подменяются в тесте, чтобы не ждать вживую. */
  now?: () => number
}

/**
 * Заказывает разбор и ждёт его.
 *
 * Возвращает текст целиком: поток машина не отдаёт — Claude Code в headless
 * пишет ответ одним куском, и притворяться, что он печатается, было бы обманом
 * ожидания.
 */
export async function askWhy(token: string, a: WhyAsk, opts: AskOptions = {}): Promise<string> {
  if (!token) throw new CoachError(0, 'не задан токен разбора — впишите его в настройках')

  const шаг = opts.pollMs ?? POLL_MS
  const потолок = opts.waitMs ?? WAIT_MS
  const часы = opts.now ?? (() => Date.now())

  const заказ = await запрос(WHY_URL, token, whyBody(a))
  // Тот же разбор уже кто-то заказывал — очередь отдаёт его сразу, без машины.
  if (заказ.state === 'done' && заказ.text) return заказ.text
  if (!заказ.id) throw new CoachError(0, 'очередь не выдала номер разбора')

  opts.onStage?.('заказано')

  const начало = часы()
  let стадия: WhyStage = 'заказано'
  let pcAgo = заказ.pcAgo ?? null

  for (;;) {
    await пауза(шаг)
    const ответ = await запрос(`${WHY_URL}?id=${encodeURIComponent(заказ.id)}`, token)
    pcAgo = ответ.pcAgo ?? null

    if (ответ.state === 'done') {
      if (!ответ.text) throw new CoachError(0, 'машина вернула пустой разбор')
      return ответ.text
    }
    // Наряд протух: машину не дождались, и она его уже не возьмёт.
    if (ответ.state === 'expired') throw new CoachError(0, поЧемуМолчит(pcAgo))
    if (ответ.state === 'taken' && стадия !== 'машина пишет') {
      стадия = 'машина пишет'
      opts.onStage?.(стадия)
    }
    if (часы() - начало >= потолок) throw new CoachError(0, поЧемуМолчит(pcAgo))
  }
}
