/**
 * Часы чтения: сколько времени человек ПРОВЁЛ НАД ТЕКСТОМ.
 *
 * До 22.08.2026 приложение не мерило чтение вовсе. Экран чтения писал в журнал две
 * вещи — отметки незнакомых слов (`mark`) и факт прочтения (`reading`), — и обе без
 * длительности. Минуты чтения (`readMinutesByDay`) считаются только по строкам `read`,
 * а их писала единственная кнопка «+» на главной, где минуты вводятся руками. Живой
 * случай 22.08: 22 отметки и одно прочтение, между первой отметкой и «Я дочитал»
 * четыре с лишним минуты, полоса дня — «чтение 0/30 мин». Арифметика была верна, вход
 * пуст. Половина защищённого минимума, которую нечем измерить, отмирает первой — ровно
 * это и записано в обосновании самой кнопки.
 *
 * Модуль намеренно чистый (никакого DOM и никаких таймеров): состояние — обычный
 * объект, время приходит аргументом. Поэтому часы проверяются в Node построчно, а не
 * догадками про поведение вкладки.
 *
 * ЧТО СЧИТАЕТСЯ ЧТЕНИЕМ. Промежуток идёт в зачёт, если текст на экране (`active`) И с
 * последнего действия человека прошло меньше `READ_IDLE_MS`. Второе условие — защита
 * от «открыл и ушёл»: на телефоне уход закрывает `visibilitychange`, но оставленная
 * открытой вкладка на ноутбуке ничего не сообщает. Само чтение действий не требует —
 * человек смотрит в экран и молчит, — поэтому порог простоя большой и ошибается в
 * сторону недосчёта: тексты здесь на 130–400 слов, три минуты без единого касания на
 * таком объёме означают, что читателя нет.
 */

/** Три минуты без единого действия — читателя за экраном нет. */
export const READ_IDLE_MS = 180_000

/** Меньше получаса секунд — не заход чтения, а случайное открытие текста. */
export const READ_MIN_CREDIT_S = 30

export interface ReadClock {
  /** секунды, зачтённые и ещё НЕ записанные в журнал */
  credited: number
  /** секунды за весь заход, включая уже записанные, — по ним считается темп чтения */
  total: number
  /** момент последнего пересчёта */
  last: number
  /** момент последнего действия человека: касание, прокрутка, клавиша */
  acted: number
  /** текст на экране и читается (не скрыт, не дочитан) */
  active: boolean
}

export function startClock(now: number): ReadClock {
  return { credited: 0, total: 0, last: now, acted: now, active: true }
}

/**
 * Пересчёт до момента `now`: зачесть промежуток от прошлого пересчёта, если он засчитываемый.
 *
 * Промежуток целиком либо идёт в зачёт, либо не идёт. Делить его пополам по моменту, когда
 * истёк простой, здесь нечем: между двумя пересчётами приложение не знает, что происходило.
 * При частом пересчёте (экран тикает каждые несколько секунд) ошибка не превышает шага тика,
 * и она в сторону недосчёта.
 */
export function advance(c: ReadClock, now: number): ReadClock {
  const gap = now - c.last
  if (gap <= 0) return { ...c, last: now }
  const засчитываем = c.active && now - c.acted <= READ_IDLE_MS
  const sec = засчитываем ? gap / 1000 : 0
  return { ...c, last: now, credited: c.credited + sec, total: c.total + sec }
}

/** Человек что-то сделал: коснулся слова, прокрутил, нажал клавишу. */
export function poke(c: ReadClock, now: number): ReadClock {
  return { ...advance(c, now), acted: now }
}

/**
 * Текст ушёл с экрана или вернулся: вкладка скрылась, приложение свернули, нажато «Я дочитал».
 *
 * Возвращение засчитывается действием: человек вернулся к тексту, и отсчёт простоя начинается
 * заново. Иначе часы, простоявшие скрытыми дольше `READ_IDLE_MS`, после возвращения не
 * засчитали бы ни секунды до первого касания — а на коротком тексте касаний может не быть вовсе.
 */
export function setActive(c: ReadClock, now: number, active: boolean): ReadClock {
  const next = advance(c, now)
  return active ? { ...next, active: true, acted: now } : { ...next, active: false }
}

export interface Flush {
  /** сколько целых минут записать в журнал; 0 — писать нечего */
  minutes: number
  /** часы после съёма: записанное вычтено, остаток перенесён на следующий раз */
  rest: ReadClock
}

/**
 * Снять накопленное для записи строкой журнала.
 *
 * `final` — человек уходит с текста: остаток округляется, и полминуты уже считаются минутой.
 * Промежуточный съём (вкладку скрыли, но текст остался открыт) режет по ЦЕЛЫМ минутам и
 * переносит остаток: иначе три коротких захода по сорок секунд округлились бы вверх каждый и
 * дали бы три минуты вместо двух. Перенос остатка — единственное, что удерживает сумму дня
 * равной действительно прочитанному, сколько бы раз ни сворачивали приложение.
 */
export function flush(c: ReadClock, now: number, final: boolean): Flush {
  const s = advance(c, now)
  const minutes = final
    ? (s.credited >= READ_MIN_CREDIT_S ? Math.round(s.credited / 60) : 0)
    : Math.floor(s.credited / 60)
  return { minutes, rest: { ...s, credited: Math.max(0, s.credited - minutes * 60) } }
}
