import { Close } from './Icon'

/**
 * Desmos в практике математики. Ссылка ведёт на конфигурацию College Board - тот самый
 * калькулятор, что встроен в Bluebook на экзамене (набор функций и кнопок совпадает),
 * поэтому навык переносится один в один. Ключа API не нужно: это страница Desmos, а не
 * их библиотека. Если сайт откажется открываться во фрейме, остаётся ссылка «отдельно».
 */
export const DESMOS_URL = 'https://www.desmos.com/testing/cb-digital-sat/graphing'

/** Приёмы Desmos под задачи SAT - то, ради чего калькулятор и стоит в Bluebook. */
const TIPS: [string, string][] = [
  ['Уравнение с одной переменной', 'левую часть строкой y = …, правую - второй строкой; x точки пересечения и есть корень. Коснись точки - покажет координаты.'],
  ['Система уравнений', 'обе строки как есть (2x + 3y = 7 и x − y = 1) - решение в точке пересечения. «Сколько решений»: 0 - параллельные, бесконечно - графики совпали.'],
  ['Квадратичная функция', 'y = 2x² − 8x + 3: серые точки - вершина, нули и пересечение с осью y; коснись их. Сумма/произведение корней тоже отсюда.'],
  ['Неизвестная константа (k, a, c)', 'впиши уравнение с буквой - Desmos предложит ползунок; двигай, пока не выполнится условие (одно решение = касание, нет решений = не пересекаются).'],
  ['Функции', 'задай f(x) = …, потом просто f(3), f(a + 1) или f(g(2)) отдельной строкой - значение посчитается.'],
  ['Регрессия по таблице', '«+» → table, введи точки; строкой y₁ ~ mx₁ + b (тильда ~) получишь m и b. Квадратичная: y₁ ~ ax₁² + bx₁ + c, экспонента: y₁ ~ a·b^x₁.'],
  ['Эквивалентные выражения', 'y = (исходное) и y = (вариант ответа): совпали графики - выражения равны. Так проверяются все четыре варианта за минуту.'],
  ['Неравенства и области', 'y > 2x + 1, y ≤ −x + 5 - закраска покажет общую область; точку из вариантов вставь как (3, 4) и посмотри, где она.'],
  ['Окружность', 'x² + y² + 6x − 4y = 12 строится как есть: центр и радиус видно по графику, без выделения полного квадрата.'],
  ['Статистика', 'mean([3, 7, 8]), median([…]), stdev([…]) - для вопросов про среднее, медиану и разброс.'],
  ['Проценты и дроби', 'это ещё и обычный калькулятор: 0.35·80, 1.2^5·1000. Кнопка ⇄ у ответа переводит десятичную дробь в обыкновенную (для SPR).']
]

export function DesmosTips() {
  return (
    <details className="card desmos-tips">
      <summary>Как решать через Desmos</summary>
      <ul>
        {TIPS.map(([k, v]) => <li key={k}><b>{k}:</b> {v}</li>)}
      </ul>
      <p className="desmos-tips-note">
        Правило экзамена: сначала оцени, быстрее ли построить, чем посчитать в уме. Системы,
        квадратичные, «сколько решений» и выбор эквивалентного выражения почти всегда быстрее в Desmos.
      </p>
    </details>
  )
}

export function DesmosPanel({ open, onClose }: { open: boolean; onClose: () => void }) {
  return (
    <aside className="desmos-panel" hidden={!open} aria-label="Калькулятор Desmos">
      <div className="desmos-bar">
        <b>Desmos</b>
        <a className="desmos-ext" href={DESMOS_URL} target="_blank" rel="noopener noreferrer">открыть отдельно</a>
        <button className="iconbtn" onClick={onClose} aria-label="Скрыть Desmos"><Close /></button>
      </div>
      <DesmosTips />
      <iframe className="desmos-frame" src={DESMOS_URL} title="Desmos" allow="clipboard-read; clipboard-write" />
    </aside>
  )
}
